CREATE OR REPLACE FUNCTION public.issue_premium_credits(
  p_user_id bigint,
  p_amount numeric,
  p_source text,
  p_reference text,
  p_expiry_days integer DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_lot public.premium_credit_lots%ROWTYPE;
  v_days integer;
  v_lot_id bigint;
  v_balance numeric;
BEGIN
  IF p_user_id IS NULL OR p_user_id <= 0 THEN
    RAISE EXCEPTION 'A valid member is required';
  END IF;
  IF p_amount IS NULL OR p_amount <= 0 OR p_amount > 1000000 THEN
    RAISE EXCEPTION 'Credit amount must be between 1 and 1,000,000';
  END IF;
  IF p_reference IS NULL OR length(trim(p_reference)) < 3 THEN
    RAISE EXCEPTION 'A unique credit reference is required';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = p_user_id) THEN
    RAISE EXCEPTION 'Member not found';
  END IF;

  SELECT * INTO v_lot FROM public.premium_credit_lots WHERE reference = trim(p_reference);
  IF FOUND THEN
    RETURN jsonb_build_object(
      'success', true,
      'alreadyIssued', true,
      'lotId', v_lot.id,
      'amount', v_lot.amount,
      'expiresAt', v_lot.expires_at
    );
  END IF;

  SELECT coalesce(p_expiry_days, premium_credit_expiry_days, 90)
    INTO v_days
  FROM public.revenue_settings
  ORDER BY id
  LIMIT 1;
  v_days := greatest(coalesce(v_days, 90), 1);

  INSERT INTO public.premium_credit_lots
    (user_id, amount, remaining, source, reference, expires_at)
  VALUES
    (p_user_id, p_amount, p_amount, coalesce(nullif(trim(p_source), ''), 'MEMBERSHIP'),
     trim(p_reference), now() + make_interval(days => v_days))
  RETURNING id INTO v_lot_id;

  INSERT INTO public.premium_credit_ledger
    (user_id, lot_id, type, amount, reference, description)
  VALUES
    (p_user_id, v_lot_id, 'ISSUED', p_amount, trim(p_reference),
     format('%s promotional credits issued', p_source));

  SELECT coalesce(sum(remaining), 0) INTO v_balance
  FROM public.premium_credit_lots
  WHERE user_id = p_user_id AND remaining > 0 AND expires_at > now();

  RETURN jsonb_build_object(
    'success', true,
    'alreadyIssued', false,
    'lotId', v_lot_id,
    'amount', p_amount,
    'expiresAt', (now() + make_interval(days => v_days)),
    'balance', v_balance
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.premium_credit_balance(p_user_id bigint)
RETURNS numeric
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT coalesce(sum(remaining), 0)
  FROM public.premium_credit_lots
  WHERE user_id = p_user_id AND remaining > 0 AND expires_at > now();
$$;

CREATE OR REPLACE FUNCTION public.redeem_premium_credits(
  p_user_id bigint,
  p_max_amount numeric,
  p_reference text,
  p_description text DEFAULT ''
)
RETURNS numeric
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_lot record;
  v_take numeric;
  v_applied numeric := 0;
  v_remaining numeric := greatest(coalesce(p_max_amount, 0), 0);
BEGIN
  IF v_remaining <= 0 THEN
    RETURN 0;
  END IF;

  FOR v_lot IN
    SELECT * FROM public.premium_credit_lots
    WHERE user_id = p_user_id
      AND remaining > 0
      AND expires_at > now()
    ORDER BY expires_at ASC, id ASC
    FOR UPDATE
  LOOP
    EXIT WHEN v_remaining <= 0;
    v_take := least(v_lot.remaining, v_remaining);
    UPDATE public.premium_credit_lots
    SET remaining = remaining - v_take
    WHERE id = v_lot.id;

    INSERT INTO public.premium_credit_ledger
      (user_id, lot_id, type, amount, reference, description)
    VALUES
      (p_user_id, v_lot.id, 'REDEEMED', -v_take, coalesce(p_reference, ''),
       coalesce(nullif(trim(p_description), ''), 'Promotion credit redeemed'));

    v_applied := v_applied + v_take;
    v_remaining := v_remaining - v_take;
  END LOOP;

  RETURN v_applied;
END;
$$;

