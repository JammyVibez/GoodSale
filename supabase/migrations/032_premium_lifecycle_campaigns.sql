CREATE OR REPLACE FUNCTION public.purchase_sponsored_campaign_v2(
  p_user_id bigint,
  p_ad_type text,
  p_target_id bigint,
  p_title text,
  p_budget numeric,
  p_banner_url text DEFAULT '',
  p_placements jsonb DEFAULT '["HOME"]'::jsonb,
  p_target_state text DEFAULT '',
  p_target_city text DEFAULT '',
  p_target_category text DEFAULT '',
  p_starts_at timestamptz DEFAULT NULL,
  p_ends_at timestamptz DEFAULT NULL,
  p_daily_budget numeric DEFAULT NULL,
  p_cpc_bid numeric DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_product public.products%ROWTYPE;
  v_wallet public.wallets%ROWTYPE;
  v_cpc numeric;
  v_daily numeric;
  v_budget numeric := p_budget;
  v_ad_id bigint;
  v_balance numeric;
  v_type text := upper(trim(p_ad_type));
  v_start timestamptz := coalesce(p_starts_at, now());
  v_end timestamptz := coalesce(p_ends_at, now() + interval '30 days');
  v_placements jsonb := coalesce(p_placements, '["HOME"]'::jsonb);
  v_state text := left(trim(coalesce(p_target_state, '')), 80);
  v_city text := left(trim(coalesce(p_target_city, '')), 80);
  v_category text := left(trim(coalesce(p_target_category, '')), 80);
BEGIN
  IF p_user_id IS NULL OR p_user_id <= 0 THEN RAISE EXCEPTION 'A signed-in advertiser is required'; END IF;
  IF length(trim(coalesce(p_title, ''))) < 3 OR length(trim(p_title)) > 100 THEN
    RAISE EXCEPTION 'Campaign title must be 3–100 characters';
  END IF;
  IF v_type NOT IN ('PRODUCT', 'BUSINESS', 'BANNER_HOME', 'BANNER_CATEGORY') THEN
    RAISE EXCEPTION 'Unknown campaign type';
  END IF;
  IF v_budget IS NULL OR v_budget < 100 OR v_budget > 5000000 THEN
    RAISE EXCEPTION 'Campaign budget must be between ₦100 and ₦5,000,000';
  END IF;
  IF jsonb_typeof(v_placements) <> 'array' OR jsonb_array_length(v_placements) = 0 THEN
    RAISE EXCEPTION 'Choose at least one campaign placement';
  END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements_text(v_placements) p
    WHERE p NOT IN ('HOME', 'CATEGORY', 'DETAIL', 'CHAT', 'DASHBOARD', 'SEARCH')
  ) THEN
    RAISE EXCEPTION 'Unknown campaign placement';
  END IF;

  v_start := greatest(v_start, now());
  v_end := greatest(v_end, v_start + interval '1 hour');
  IF v_end > v_start + interval '90 days' THEN
    RAISE EXCEPTION 'Campaigns can run for at most 90 days';
  END IF;

  SELECT coalesce(ad_cpc_price, 150) INTO v_cpc
  FROM public.revenue_settings ORDER BY id LIMIT 1;
  v_cpc := coalesce(nullif(p_cpc_bid, 0), v_cpc, 150);
  IF v_cpc < 50 OR v_cpc > 10000 THEN
    RAISE EXCEPTION 'CPC bid must be between ₦50 and ₦10,000';
  END IF;
  IF v_budget < v_cpc THEN RAISE EXCEPTION 'Campaign budget must cover at least one click'; END IF;

  v_daily := coalesce(nullif(p_daily_budget, 0), v_budget);
  IF v_daily < v_cpc OR v_daily > v_budget THEN
    RAISE EXCEPTION 'Daily budget must be at least one click and no more than the total budget';
  END IF;

  IF v_type = 'PRODUCT' THEN
    SELECT * INTO v_product FROM public.products WHERE id = p_target_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Promoted listing not found'; END IF;
    IF v_product.seller_id <> p_user_id THEN RAISE EXCEPTION 'You can only advertise your own listing'; END IF;
    IF v_product.stock_status NOT IN ('IN_STOCK', 'LOW_STOCK') THEN
      RAISE EXCEPTION 'Only active, in-stock listings can be advertised';
    END IF;
    IF v_product.moderation_status IS NOT NULL AND v_product.moderation_status <> 'APPROVED' THEN
      RAISE EXCEPTION 'This listing is not approved for advertising';
    END IF;
    v_category := coalesce(nullif(v_category, ''), v_product.category);
  END IF;

  SELECT * INTO v_wallet FROM public.wallets WHERE user_id = p_user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Add funds to your wallet before creating a campaign'; END IF;
  IF coalesce(v_wallet.balance, 0) < v_budget THEN
    RAISE EXCEPTION 'Insufficient wallet balance for this campaign budget';
  END IF;

  v_balance := v_wallet.balance - v_budget;
  PERFORM set_config('goodsale.wallet_write', 'on', true);
  UPDATE public.wallets SET balance = v_balance WHERE id = v_wallet.id;
  INSERT INTO public.wallet_transactions
    (wallet_id, amount, type, description, status, created_at)
  VALUES
    (v_wallet.id, -v_budget, 'DEBIT_AD',
     format('Sponsored campaign budget reserved: "%s"', trim(p_title)),
     'COMPLETED', now());

  INSERT INTO public.sponsored_ads
    (seller_id, type, target_id, title, banner_url, status, budget, spent,
     clicks, impressions, moderation_status, moderation_reason, created_at,
     placements, target_state, target_city, target_category, daily_budget, cpc_bid,
     starts_at, ends_at)
  VALUES
    (p_user_id, v_type, coalesce(p_target_id, 0), trim(p_title),
     nullif(trim(coalesce(p_banner_url, '')), ''), 'PENDING_REVIEW',
     v_budget, 0, 0, 0, 'PENDING', '', now(), v_placements, v_state, v_city,
     v_category, v_daily, v_cpc, v_start, v_end)
  RETURNING id INTO v_ad_id;

  INSERT INTO public.notifications
    (user_id, title, message, type, is_read, created_at)
  VALUES
    (p_user_id, 'Campaign submitted for review',
     format('"%s" is awaiting moderation. ₦%s is reserved; the daily cap is ₦%s at a ₦%s CPC bid.',
            trim(p_title), trim(to_char(v_budget, 'FM999,999,990')),
            trim(to_char(v_daily, 'FM999,999,990')), trim(to_char(v_cpc, 'FM999,999,990'))),
     'PROMOTION', false, now());

  INSERT INTO public.audit_logs
    (user_id, action, entity_type, entity_id, details)
  VALUES
    (p_user_id, 'CREATE_SPONSORED_CAMPAIGN', 'SPONSORED_AD', v_ad_id,
     format('%s campaign; budget ₦%s; daily ₦%s; CPC ₦%s; placements %s; target %s/%s/%s',
            v_type, v_budget, v_daily, v_cpc, v_placements::text, v_state, v_city, v_category));

  RETURN jsonb_build_object(
    'success', true, 'campaignId', v_ad_id, 'status', 'PENDING_REVIEW',
    'budget', v_budget, 'dailyBudget', v_daily, 'cpc', v_cpc,
    'startsAt', v_start, 'endsAt', v_end, 'balance', v_balance
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.record_sponsored_ad_event_v2(
  p_ad_id bigint,
  p_event_type text,
  p_dedup_key text,
  p_state text DEFAULT '',
  p_city text DEFAULT '',
  p_category text DEFAULT '',
  p_order_id bigint DEFAULT NULL,
  p_order_value numeric DEFAULT 0
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_ad public.sponsored_ads%ROWTYPE;
  v_event text := upper(trim(p_event_type));
  v_cpc numeric;
  v_event_id bigint;
  v_daily_spend numeric := 0;
BEGIN
  IF v_event NOT IN ('IMPRESSION', 'CLICK', 'CONVERSION') THEN RAISE EXCEPTION 'Unknown ad event'; END IF;
  IF p_dedup_key IS NULL OR length(trim(p_dedup_key)) = 0 THEN RAISE EXCEPTION 'An event identity is required'; END IF;

  SELECT * INTO v_ad FROM public.sponsored_ads WHERE id = p_ad_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Campaign not found'; END IF;
  IF v_ad.moderation_status NOT IN ('APPROVED') THEN
    RETURN jsonb_build_object('success', false, 'reason', 'campaign_not_approved');
  END IF;

  IF v_event = 'CONVERSION' THEN
    IF p_order_id IS NULL OR p_order_id <= 0 THEN RAISE EXCEPTION 'An order is required for a conversion'; END IF;
    INSERT INTO public.sponsored_ad_events (ad_id, event_type, dedup_key, order_id, value)
    VALUES (p_ad_id, 'CONVERSION', 'ORDER:' || p_order_id::text, p_order_id, greatest(coalesce(p_order_value, 0), 0))
    ON CONFLICT (ad_id, event_type, dedup_key) DO NOTHING
    RETURNING id INTO v_event_id;
    IF v_event_id IS NULL THEN RETURN jsonb_build_object('success', true, 'deduplicated', true); END IF;
    UPDATE public.sponsored_ads
    SET conversions = conversions + 1,
        conversion_value = conversion_value + greatest(coalesce(p_order_value, 0), 0)
    WHERE id = p_ad_id;
    RETURN jsonb_build_object('success', true, 'deduplicated', false);
  END IF;

  IF v_ad.status <> 'ACTIVE' THEN
    RETURN jsonb_build_object('success', false, 'reason', 'campaign_not_active');
  END IF;
  IF v_ad.starts_at IS NOT NULL AND v_ad.starts_at > now() THEN
    RETURN jsonb_build_object('success', false, 'reason', 'campaign_not_started');
  END IF;
  IF v_ad.ends_at IS NOT NULL AND v_ad.ends_at <= now() THEN
    UPDATE public.sponsored_ads SET status = 'COMPLETED' WHERE id = p_ad_id;
    RETURN jsonb_build_object('success', false, 'reason', 'campaign_ended');
  END IF;

  IF v_ad.target_state <> '' AND lower(v_ad.target_state) <> lower(trim(coalesce(p_state, ''))) THEN
    RETURN jsonb_build_object('success', false, 'reason', 'state_target_mismatch');
  END IF;
  IF v_ad.target_city <> '' AND lower(v_ad.target_city) <> lower(trim(coalesce(p_city, ''))) THEN
    RETURN jsonb_build_object('success', false, 'reason', 'city_target_mismatch');
  END IF;
  IF v_ad.target_category <> '' AND lower(v_ad.target_category) <> lower(trim(coalesce(p_category, ''))) THEN
    RETURN jsonb_build_object('success', false, 'reason', 'category_target_mismatch');
  END IF;

  IF v_event = 'CLICK' THEN
    v_cpc := coalesce(nullif(v_ad.cpc_bid, 0), 150);
    SELECT coalesce(sum(spend), 0) INTO v_daily_spend
    FROM public.sponsored_ad_daily_spend
    WHERE ad_id = p_ad_id AND spend_date = current_date;

    IF v_ad.daily_budget > 0 AND v_daily_spend + v_cpc > v_ad.daily_budget THEN
      RETURN jsonb_build_object('success', false, 'reason', 'daily_budget_exhausted');
    END IF;
    IF v_ad.spent + v_cpc > v_ad.budget THEN
      UPDATE public.sponsored_ads SET status = 'COMPLETED' WHERE id = p_ad_id;
      RETURN jsonb_build_object('success', false, 'reason', 'budget_exhausted');
    END IF;
  END IF;

  INSERT INTO public.sponsored_ad_events (ad_id, event_type, dedup_key)
  VALUES (p_ad_id, v_event, p_dedup_key)
  ON CONFLICT (ad_id, event_type, dedup_key) DO NOTHING
  RETURNING id INTO v_event_id;

  IF v_event_id IS NULL THEN RETURN jsonb_build_object('success', true, 'deduplicated', true); END IF;

  IF v_event = 'IMPRESSION' THEN
    UPDATE public.sponsored_ads SET impressions = impressions + 1 WHERE id = p_ad_id;
  ELSE
    UPDATE public.sponsored_ads
    SET clicks = clicks + 1,
        spent = spent + v_cpc,
        status = CASE WHEN spent + v_cpc >= budget THEN 'COMPLETED' ELSE status END
    WHERE id = p_ad_id;
    INSERT INTO public.sponsored_ad_daily_spend (ad_id, spend_date, spend, clicks)
    VALUES (p_ad_id, current_date, v_cpc, 1)
    ON CONFLICT (ad_id, spend_date)
    DO UPDATE SET spend = sponsored_ad_daily_spend.spend + EXCLUDED.spend,
                  clicks = sponsored_ad_daily_spend.clicks + 1;
  END IF;

  RETURN jsonb_build_object('success', true, 'deduplicated', false, 'spend', CASE WHEN v_event = 'CLICK' THEN v_cpc ELSE 0 END);
END;
$$;

