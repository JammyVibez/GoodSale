END;
$$;

CREATE OR REPLACE FUNCTION public.admin_review_flash_sale(
  p_promotion_id bigint,
  p_admin_id bigint,
  p_action text,
  p_reason text DEFAULT ''
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_sale public.featured_listings%ROWTYPE;
  v_action text := upper(trim(p_action));
  v_wallet public.wallets%ROWTYPE;
  v_balance numeric;
  v_status text;
BEGIN
  IF v_action NOT IN ('APPROVE', 'REJECT') THEN RAISE EXCEPTION 'Unknown moderation action'; END IF;
  IF v_action = 'REJECT' AND length(trim(coalesce(p_reason, ''))) < 3 THEN
    RAISE EXCEPTION 'A rejection reason is required';
  END IF;

  SELECT * INTO v_sale FROM public.featured_listings
  WHERE id = p_promotion_id AND feature_type = 'FLASH_SALE'
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Flash Sale not found'; END IF;
  IF v_sale.status <> 'PENDING_REVIEW' THEN RAISE EXCEPTION 'This Flash Sale is already moderated'; END IF;

  IF v_action = 'APPROVE' THEN
    v_status := CASE WHEN v_sale.starts_at > now() THEN 'SCHEDULED' ELSE 'ACTIVE' END;
    UPDATE public.featured_listings
    SET status = v_status, moderation_status = 'APPROVED', moderation_reason = '',
        approved_by = p_admin_id, approved_at = now()
    WHERE id = p_promotion_id;

    IF v_status = 'ACTIVE' THEN
      UPDATE public.products
      SET flash_sale_price = v_sale.sale_price,
          flash_sale_starts_at = v_sale.starts_at,
          flash_sale_ends_at = v_sale.ends_at
      WHERE id = v_sale.product_id;
    END IF;
  ELSE
    v_status := 'REJECTED';
    UPDATE public.featured_listings
    SET status = 'REJECTED', moderation_status = 'REJECTED',
        moderation_reason = trim(p_reason), approved_by = p_admin_id, approved_at = now()
    WHERE id = p_promotion_id;

    IF v_sale.wallet_charge > 0 THEN
      SELECT * INTO v_wallet FROM public.wallets WHERE user_id = v_sale.seller_id FOR UPDATE;
      IF FOUND THEN
        v_balance := coalesce(v_wallet.balance, 0) + v_sale.wallet_charge;
        PERFORM set_config('goodsale.wallet_write', 'on', true);
        UPDATE public.wallets SET balance = v_balance WHERE id = v_wallet.id;
        INSERT INTO public.wallet_transactions
          (wallet_id, amount, type, description, status, created_at)
        VALUES
          (v_wallet.id, v_sale.wallet_charge, 'REFUND',
           'Flash Sale rejected — wallet charge returned', 'COMPLETED', now());
      END IF;
    END IF;
    IF v_sale.credits_applied > 0 THEN
      PERFORM public.issue_premium_credits(
        v_sale.seller_id, v_sale.credits_applied, 'FLASH_SALE_REFUND',
        'FLASH_REFUND:' || v_sale.id, NULL
      );
    END IF;
  END IF;

  INSERT INTO public.audit_logs
    (user_id, action, entity_type, entity_id, details)
  VALUES
    (p_admin_id,
     CASE WHEN v_action = 'APPROVE' THEN 'APPROVE_FLASH_SALE' ELSE 'REJECT_FLASH_SALE' END,
     'FEATURED_LISTING', p_promotion_id,
     format('%s Flash Sale. %s', v_action, coalesce(p_reason, '')));

  INSERT INTO public.notifications
    (user_id, title, message, type, is_read, created_at)
  VALUES
    (v_sale.seller_id,
     CASE WHEN v_action = 'APPROVE' THEN 'Flash Sale approved' ELSE 'Flash Sale rejected' END,
     CASE WHEN v_action = 'APPROVE'
       THEN format('Your Flash Sale is %s. It starts at the scheduled time and ends 24 hours later.',
                   lower(v_status))
       ELSE format('Your Flash Sale was rejected. The wallet charge was returned and credits restored. %s',
                   trim(coalesce(p_reason, '')))
     END,
     'PROMOTION', false, now());

  RETURN jsonb_build_object('success', true, 'promotionId', p_promotion_id, 'status', v_status,
    'refunded', CASE WHEN v_action = 'REJECT' THEN v_sale.wallet_charge ELSE 0 END,
    'creditsRestored', CASE WHEN v_action = 'REJECT' THEN v_sale.credits_applied ELSE 0 END);
END;
$$;

