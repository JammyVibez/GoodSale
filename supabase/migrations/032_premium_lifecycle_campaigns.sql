CREATE OR REPLACE FUNCTION public.run_premium_jobs()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  r record;
  v_reminder_days integer;
  v_expired_business integer := 0;
  v_expired_verified integer := 0;
  v_reminders integer := 0;
  v_expired_credits numeric := 0;
  v_activated integer := 0;
  v_expired_promotions integer := 0;
  v_expired_ads integer := 0;
BEGIN
  SELECT greatest(coalesce(premium_reminder_days, 3), 1) INTO v_reminder_days
  FROM public.revenue_settings ORDER BY id LIMIT 1;
  v_reminder_days := coalesce(v_reminder_days, 3);

  UPDATE public.business_subscriptions
  SET status = 'EXPIRED'
  WHERE status = 'ACTIVE' AND expires_at <= now();
  GET DIAGNOSTICS v_expired_business = ROW_COUNT;
  UPDATE public.verified_plus_subscriptions
  SET status = 'EXPIRED'
  WHERE status = 'ACTIVE' AND expires_at <= now();
  GET DIAGNOSTICS v_expired_verified = ROW_COUNT;

  FOR r IN
    SELECT user_id, plan, expires_at FROM public.business_subscriptions
    WHERE status = 'ACTIVE' AND expires_at > now()
      AND expires_at <= now() + make_interval(days => v_reminder_days)
      AND (last_reminder_at IS NULL OR last_reminder_at < now() - interval '7 days')
  LOOP
    INSERT INTO public.notifications (user_id, title, message, type, is_read, created_at)
    VALUES (r.user_id, 'Business membership renews soon',
      format('Your Business %s membership ends %s. Renew from the Revenue Centre to keep business tools active.',
             r.plan, to_char(r.expires_at AT TIME ZONE 'Africa/Lagos', 'DD Mon YYYY')), 'WALLET', false, now());
    UPDATE public.business_subscriptions
    SET last_reminder_at = now()
    WHERE user_id = r.user_id AND plan = r.plan AND expires_at = r.expires_at;
    v_reminders := v_reminders + 1;
  END LOOP;

  FOR r IN
    SELECT user_id, expires_at FROM public.verified_plus_subscriptions
    WHERE status = 'ACTIVE' AND expires_at > now()
      AND expires_at <= now() + make_interval(days => v_reminder_days)
      AND (last_reminder_at IS NULL OR last_reminder_at < now() - interval '7 days')
  LOOP
    INSERT INTO public.notifications (user_id, title, message, type, is_read, created_at)
    VALUES (r.user_id, 'Verified+ membership renews soon',
      format('Your Verified+ membership ends %s. Renew from the Revenue Centre to keep member benefits.',
             to_char(r.expires_at AT TIME ZONE 'Africa/Lagos', 'DD Mon YYYY')), 'WALLET', false, now());
    UPDATE public.verified_plus_subscriptions
    SET last_reminder_at = now()
    WHERE user_id = r.user_id AND expires_at = r.expires_at;
    v_reminders := v_reminders + 1;
  END LOOP;

  FOR r IN
    SELECT user_id, plan, expires_at FROM public.business_subscriptions
    WHERE status = 'EXPIRED' AND expired_notified_at IS NULL
  LOOP
    INSERT INTO public.notifications (user_id, title, message, type, is_read, created_at)
    VALUES (r.user_id, 'Business membership ended',
      format('Your Business %s membership ended %s. Your listings and order history are unchanged.',
             r.plan, to_char(r.expires_at AT TIME ZONE 'Africa/Lagos', 'DD Mon YYYY')), 'WALLET', false, now());
    UPDATE public.business_subscriptions SET expired_notified_at = now()
    WHERE user_id = r.user_id AND plan = r.plan AND expires_at = r.expires_at;
  END LOOP;

  FOR r IN
    SELECT user_id, expires_at FROM public.verified_plus_subscriptions
    WHERE status = 'EXPIRED' AND expired_notified_at IS NULL
  LOOP
    INSERT INTO public.notifications (user_id, title, message, type, is_read, created_at)
    VALUES (r.user_id, 'Verified+ membership ended',
      format('Your Verified+ membership ended %s. Identity verification is separate and unchanged.',
             to_char(r.expires_at AT TIME ZONE 'Africa/Lagos', 'DD Mon YYYY')), 'WALLET', false, now());
    UPDATE public.verified_plus_subscriptions SET expired_notified_at = now()
    WHERE user_id = r.user_id AND expires_at = r.expires_at;
  END LOOP;

  FOR r IN
    SELECT * FROM public.premium_credit_lots
    WHERE remaining > 0 AND expires_at <= now()
    FOR UPDATE
  LOOP
    UPDATE public.premium_credit_lots SET remaining = 0 WHERE id = r.id;
    INSERT INTO public.premium_credit_ledger
      (user_id, lot_id, type, amount, reference, description)
    VALUES
      (r.user_id, r.id, 'EXPIRED', -r.remaining, r.reference, 'Promotional credits expired');
    v_expired_credits := v_expired_credits + r.remaining;
  END LOOP;

  UPDATE public.featured_listings
  SET status = 'ACTIVE'
  WHERE feature_type = 'FLASH_SALE' AND status = 'SCHEDULED'
    AND starts_at <= now() AND ends_at > now();
  GET DIAGNOSTICS v_activated = ROW_COUNT;

  UPDATE public.featured_listings
  SET status = 'EXPIRED'
  WHERE status IN ('ACTIVE', 'SCHEDULED') AND ends_at <= now();
  GET DIAGNOSTICS v_expired_promotions = ROW_COUNT;

  UPDATE public.products SET flash_sale_price = NULL, flash_sale_starts_at = NULL, flash_sale_ends_at = NULL
  WHERE flash_sale_ends_at IS NOT NULL AND flash_sale_ends_at <= now();

  UPDATE public.products p
  SET flash_sale_price = f.sale_price,
      flash_sale_starts_at = f.starts_at,
      flash_sale_ends_at = f.ends_at
  FROM (
    SELECT DISTINCT ON (product_id) product_id, sale_price, starts_at, ends_at
    FROM public.featured_listings
    WHERE feature_type = 'FLASH_SALE' AND status = 'ACTIVE'
      AND starts_at <= now() AND ends_at > now()
    ORDER BY product_id, starts_at DESC
  ) f
  WHERE p.id = f.product_id;

  UPDATE public.sponsored_ads
  SET status = 'COMPLETED'
  WHERE status = 'ACTIVE' AND ends_at IS NOT NULL AND ends_at <= now();
  GET DIAGNOSTICS v_expired_ads = ROW_COUNT;

  RETURN jsonb_build_object(
    'success', true,
    'businessExpired', v_expired_business,
    'verifiedExpired', v_expired_verified,
    'reminders', v_reminders,
    'creditsExpired', v_expired_credits,
    'flashActivated', v_activated,
    'promotionsExpired', v_expired_promotions,
    'adsCompleted', v_expired_ads
  );
END;
