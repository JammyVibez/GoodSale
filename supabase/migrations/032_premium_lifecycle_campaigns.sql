            v_product.title, to_char(v_start AT TIME ZONE 'Africa/Lagos', 'DD Mon YYYY HH24:MI'),
            trim(to_char(p_sale_price, 'FM999,999,990')), v_cost),
     'PROMOTION', false, now());

  INSERT INTO public.audit_logs
    (user_id, action, entity_type, entity_id, details)
  VALUES
    (p_user_id, 'SUBMIT_FLASH_SALE', 'FEATURED_LISTING', v_promotion_id,
     format('Sale price ₦%s; starts %s; quantity %s; credits ₦%s; wallet ₦%s; reference %s',
            p_sale_price, v_start, v_quantity, v_credits, v_wallet_charge, v_reference));

  RETURN jsonb_build_object(
    'success', true, 'promotionId', v_promotion_id, 'featureType', 'FLASH_SALE',
    'status', 'PENDING_REVIEW', 'amountCharged', v_wallet_charge,
    'creditsApplied', v_credits, 'balance', v_balance, 'salePrice', p_sale_price,
    'quantityLimit', v_quantity, 'startsAt', v_start, 'expiresAt', v_end,
    'reference', v_reference
