CREATE OR REPLACE FUNCTION public.purchase_featured_promotion(
  p_user_id bigint,
  p_product_id bigint,
  p_duration_days integer DEFAULT 7,
  p_use_credits boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_product public.products%ROWTYPE;
  v_wallet public.wallets%ROWTYPE;
  v_cost numeric;
  v_credits numeric := 0;
  v_wallet_charge numeric := 0;
  v_reference text;
  v_promotion_id bigint;
  v_start timestamptz := now();
  v_end timestamptz;
  v_balance numeric;
  v_duration integer := p_duration_days;
BEGIN
  IF p_user_id IS NULL OR p_user_id <= 0 THEN
    RAISE EXCEPTION 'A signed-in seller is required';
  END IF;
  IF v_duration NOT IN (3, 7, 14) THEN
    RAISE EXCEPTION 'Featured promotions are available for 3, 7 or 14 days';
  END IF;

  SELECT * INTO v_product FROM public.products WHERE id = p_product_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Listing not found'; END IF;
  IF v_product.seller_id <> p_user_id THEN RAISE EXCEPTION 'You can only promote your own listing'; END IF;
  IF v_product.stock_status NOT IN ('IN_STOCK', 'LOW_STOCK') THEN
    RAISE EXCEPTION 'Only active, in-stock listings can be promoted';
  END IF;
  IF v_product.moderation_status IS NOT NULL AND v_product.moderation_status <> 'APPROVED' THEN
    RAISE EXCEPTION 'This listing is not approved for promotion';
  END IF;

  SELECT CASE v_duration
    WHEN 3 THEN coalesce(featured_3_days_price, 2500)
    WHEN 7 THEN coalesce(featured_7_days_price, 5000)
    ELSE coalesce(featured_14_days_price, 9000)
  END INTO v_cost
  FROM public.revenue_settings ORDER BY id LIMIT 1;
  v_cost := coalesce(v_cost, 0);
  IF v_cost <= 0 THEN RAISE EXCEPTION 'This promotion is not available for purchase right now'; END IF;

  SELECT * INTO v_wallet FROM public.wallets WHERE user_id = p_user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Add funds to your wallet before buying a promotion'; END IF;

  v_reference := format('GPF_%s_%s', p_user_id, extract(epoch from clock_timestamp())::bigint);
  IF p_use_credits THEN
    v_credits := public.redeem_premium_credits(
      p_user_id, v_cost, v_reference, format('Featured listing %s days', v_duration)
    );
  END IF;
  v_wallet_charge := v_cost - v_credits;

  IF v_wallet.balance < v_wallet_charge THEN
    RAISE EXCEPTION 'Insufficient wallet balance for this promotion';
  END IF;

  v_end := v_start + make_interval(days => v_duration);
  v_balance := v_wallet.balance - v_wallet_charge;
  IF v_wallet_charge > 0 THEN
    PERFORM set_config('goodsale.wallet_write', 'on', true);
    UPDATE public.wallets SET balance = v_balance WHERE id = v_wallet.id;
    INSERT INTO public.wallet_transactions
      (wallet_id, amount, type, description, status, created_at)
    VALUES
      (v_wallet.id, -v_wallet_charge, 'DEBIT_FEES',
       format('Featured listing for "%s" (%s days); ₦%s credits applied',
              v_product.title, v_duration, trim(to_char(v_credits, 'FM999,999,990'))),
       'COMPLETED', now());
  END IF;

  INSERT INTO public.featured_listings
    (product_id, seller_id, duration_days, expires_at, status, feature_type,
     starts_at, ends_at, amount_paid, payment_reference, credits_applied, wallet_charge)
  VALUES
    (p_product_id, p_user_id, v_duration, v_end, 'ACTIVE', 'FEATURED',
     v_start, v_end, v_cost, v_reference, v_credits, v_wallet_charge)
  RETURNING id INTO v_promotion_id;

  INSERT INTO public.notifications
    (user_id, title, message, type, is_read, created_at)
  VALUES
    (p_user_id, 'Listing featured',
     format('"%s" is promoted for %s days, until %s. ₦%s in credits were applied.',
            v_product.title, v_duration,
            to_char(v_end AT TIME ZONE 'Africa/Lagos', 'DD Mon YYYY HH24:MI'), v_credits),
     'PROMOTION', false, now());

  INSERT INTO public.audit_logs
    (user_id, action, entity_type, entity_id, details)
  VALUES
    (p_user_id, 'PURCHASE_LISTING_PROMOTION', 'FEATURED_LISTING', v_promotion_id,
     format('FEATURED %s days; price ₦%s; credits ₦%s; wallet ₦%s; reference %s',
            v_duration, v_cost, v_credits, v_wallet_charge, v_reference));

  RETURN jsonb_build_object(
    'success', true, 'promotionId', v_promotion_id, 'featureType', 'FEATURED',
    'durationDays', v_duration, 'amountCharged', v_wallet_charge,
    'creditsApplied', v_credits, 'balance', v_balance, 'startsAt', v_start,
    'expiresAt', v_end, 'reference', v_reference
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.purchase_flash_sale(
  p_user_id bigint,
  p_product_id bigint,
  p_sale_price numeric,
  p_starts_at timestamptz DEFAULT NULL,
  p_quantity_limit integer DEFAULT NULL,
  p_use_credits boolean DEFAULT true
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_product public.products%ROWTYPE;
  v_wallet public.wallets%ROWTYPE;
  v_cost numeric;
  v_credits numeric := 0;
  v_wallet_charge numeric := 0;
  v_reference text;
  v_promotion_id bigint;
  v_start timestamptz;
  v_end timestamptz;
  v_balance numeric;
  v_quantity integer;
BEGIN
  IF p_user_id IS NULL OR p_user_id <= 0 THEN RAISE EXCEPTION 'A signed-in seller is required'; END IF;

  SELECT * INTO v_product FROM public.products WHERE id = p_product_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Listing not found'; END IF;
  IF v_product.seller_id <> p_user_id THEN RAISE EXCEPTION 'You can only promote your own listing'; END IF;
  IF v_product.stock_status NOT IN ('IN_STOCK', 'LOW_STOCK') THEN
    RAISE EXCEPTION 'Only active, in-stock listings can run a Flash Sale';
  END IF;
  IF v_product.moderation_status IS NOT NULL AND v_product.moderation_status <> 'APPROVED' THEN
    RAISE EXCEPTION 'This listing is not approved for promotion';
  END IF;
  IF p_sale_price IS NULL OR p_sale_price <= 0 OR p_sale_price >= v_product.price THEN
    RAISE EXCEPTION 'The Flash Sale price must be lower than the current listing price';
  END IF;
  IF p_sale_price < round(v_product.price * 0.10, 2) THEN
    RAISE EXCEPTION 'Flash Sale discounts are capped at 90 percent off';
  END IF;

  v_quantity := least(greatest(coalesce(p_quantity_limit, v_product.quantity), 1), v_product.quantity);
  v_start := greatest(coalesce(p_starts_at, now()), now() + interval '1 minute');
  IF v_start > now() + interval '30 days' THEN
    RAISE EXCEPTION 'Flash Sales can be scheduled at most 30 days ahead';
  END IF;
  v_end := v_start + interval '24 hours';

  IF EXISTS (
    SELECT 1 FROM public.featured_listings
    WHERE product_id = p_product_id
      AND feature_type = 'FLASH_SALE'
      AND status IN ('PENDING_REVIEW', 'SCHEDULED', 'ACTIVE')
      AND ends_at > v_start
      AND starts_at < v_end
  ) THEN
    RAISE EXCEPTION 'This listing already has a pending or scheduled Flash Sale in that window';
  END IF;

  SELECT coalesce(flash_sale_feature_price, 7500)
    INTO v_cost
  FROM public.revenue_settings ORDER BY id LIMIT 1;
  v_cost := coalesce(v_cost, 0);
  IF v_cost <= 0 THEN RAISE EXCEPTION 'Flash Sales are not available for purchase right now'; END IF;

  SELECT * INTO v_wallet FROM public.wallets WHERE user_id = p_user_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Add funds to your wallet before buying a Flash Sale'; END IF;

  v_reference := format('GFS_%s_%s', p_user_id, extract(epoch from clock_timestamp())::bigint);
  IF p_use_credits THEN
    v_credits := public.redeem_premium_credits(
      p_user_id, v_cost, v_reference, format('Flash Sale for %s', v_product.title)
    );
  END IF;
  v_wallet_charge := v_cost - v_credits;
  IF v_wallet.balance < v_wallet_charge THEN
    RAISE EXCEPTION 'Insufficient wallet balance for this Flash Sale';
  END IF;

  v_balance := v_wallet.balance - v_wallet_charge;
  IF v_wallet_charge > 0 THEN
    PERFORM set_config('goodsale.wallet_write', 'on', true);
    UPDATE public.wallets SET balance = v_balance WHERE id = v_wallet.id;
    INSERT INTO public.wallet_transactions
      (wallet_id, amount, type, description, status, created_at)
    VALUES
      (v_wallet.id, -v_wallet_charge, 'DEBIT_FEES',
       format('Flash Sale for "%s"; ₦%s credits applied',
              v_product.title, trim(to_char(v_credits, 'FM999,999,990'))),
       'COMPLETED', now());
  END IF;

  INSERT INTO public.featured_listings
    (product_id, seller_id, duration_days, expires_at, status, feature_type,
     starts_at, ends_at, amount_paid, payment_reference, credits_applied, wallet_charge,
     sale_price, quantity_limit, quantity_sold, moderation_status, moderation_reason)
  VALUES
    (p_product_id, p_user_id, 1, v_end, 'PENDING_REVIEW', 'FLASH_SALE',
     v_start, v_end, v_cost, v_reference, v_credits, v_wallet_charge,
     p_sale_price, v_quantity, 0, 'PENDING', '')
  RETURNING id INTO v_promotion_id;

  INSERT INTO public.notifications
    (user_id, title, message, type, is_read, created_at)
  VALUES
    (p_user_id, 'Flash Sale submitted for review',
