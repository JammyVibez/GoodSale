-- Credits are issued exactly once when a verified membership payment activates.
CREATE OR REPLACE FUNCTION public.issue_membership_credits_after_payment()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_amount numeric := 0;
  v_plan text;
BEGIN
  IF NEW.status <> 'SUCCESS' OR (TG_OP = 'UPDATE' AND OLD.status IS NOT DISTINCT FROM 'SUCCESS') THEN
    RETURN NEW;
  END IF;

  IF NEW.product = 'VERIFIED_PLUS' THEN
    SELECT verified_plus_monthly_credits INTO v_amount
    FROM public.revenue_settings ORDER BY id LIMIT 1;
    v_plan := 'VERIFIED_PLUS';
  ELSE
    v_plan := upper(coalesce(NEW.plan_code, 'PRO'));
    SELECT CASE v_plan
      WHEN 'ENTERPRISE' THEN business_enterprise_monthly_credits
      WHEN 'PREMIUM' THEN business_premium_monthly_credits
      ELSE business_pro_monthly_credits
    END INTO v_amount
    FROM public.revenue_settings ORDER BY id LIMIT 1;
  END IF;

  IF coalesce(v_amount, 0) > 0 THEN
    PERFORM public.issue_premium_credits(
      NEW.user_id,
      v_amount,
      'MEMBERSHIP',
      'MEMBERSHIP_CREDIT:' || NEW.reference,
      NULL
    );
  END IF;
  RETURN NEW;
END;
$$;

