-- ---------------------------------------------------------------------------
-- One-time delivery confirmation code
-- ---------------------------------------------------------------------------
create or replace function public.delivery_generate_confirmation_code(p_delivery_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  d public.deliveries%ROWTYPE;
  caller bigint := public.current_profile_id();
  v_code text;
  v_salt text;
  v_expires timestamptz := now() + interval '24 hours';
begin
  if caller is null then
    raise exception 'Not authenticated';
  end if;

  select * into d from public.deliveries where id = p_delivery_id for update;
  if not found then
    raise exception 'Delivery not found';
  end if;

  -- Only the buyer on this order may ever see the code.
  if d.buyer_id <> caller then
    raise exception 'Only the buyer can view the delivery confirmation code';
  end if;

  if d.status in ('DELIVERED', 'CANCELLED', 'RETURNED_TO_SELLER') then
    raise exception 'Delivery is already closed';
  end if;

  v_code := lpad((floor(random() * 900000) + 100000)::int::text, 6, '0');
  v_salt := md5(random()::text || clock_timestamp()::text || d.id::text || caller::text);

  update public.deliveries
     set confirmation_hash = encode(sha256(convert_to(v_code || v_salt, 'UTF8')), 'hex'),
         confirmation_salt = v_salt,
         confirmation_expires_at = v_expires,
         confirmation_attempts = 0,
         confirmation_locked_until = null,
         updated_at = now()
   where id = d.id;

  perform public.delivery_audit(d.id, 'CONFIRMATION_CODE_ISSUED', d.status, d.status,
                                'Buyer generated a one-time confirmation code');

  return jsonb_build_object('success', true, 'code', v_code, 'expires_at', v_expires);
end;
$$;

create or replace function public.delivery_confirm_with_code(p_delivery_id bigint, p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  d public.deliveries%ROWTYPE;
  caller bigint := public.current_profile_id();
  v_code text := btrim(coalesce(p_code, ''));
  v_is_rider boolean;
  v_attempts integer;
begin
  if caller is null then
    raise exception 'Not authenticated';
  end if;

  select * into d from public.deliveries where id = p_delivery_id for update;
  if not found then
    raise exception 'Delivery not found';
  end if;

  v_is_rider := public.delivery_caller_is_rider(d);
  if not v_is_rider and not public.is_admin() then
    raise exception 'Only the assigned rider or an authorized operator can confirm delivery';
  end if;

  if d.status = 'DELIVERED' then
    return jsonb_build_object('success', true, 'already_delivered', true);
  end if;
  if d.status in ('CANCELLED', 'RETURNED_TO_SELLER') then
    raise exception 'Delivery is closed';
  end if;
  if d.status <> 'OUT_FOR_DELIVERY' and d.status <> 'DELIVERY_ATTEMPTED' then
    raise exception 'Delivery must be out for delivery before it can be confirmed';
  end if;
  if not v_code ~ '^[0-9]{4,8}$' then
    raise exception 'Enter the buyer confirmation code';
  end if;

  if d.confirmation_hash is null or d.confirmation_salt is null then
    raise exception 'The buyer has not generated a confirmation code yet';
  end if;
  if d.confirmation_locked_until is not null and d.confirmation_locked_until > now() then
    raise exception 'Too many incorrect attempts. Try again after the lock expires.';
  end if;
  if d.confirmation_expires_at is null or d.confirmation_expires_at <= now() then
    raise exception 'The confirmation code has expired. Ask the buyer for a new one.';
  end if;

  if encode(sha256(convert_to(v_code || d.confirmation_salt, 'UTF8')), 'hex') <> d.confirmation_hash then
    v_attempts := d.confirmation_attempts + 1;
    update public.deliveries
       set confirmation_attempts = v_attempts,
           confirmation_locked_until = case when v_attempts >= 5 then now() + interval '15 minutes' else null end,
           updated_at = now()
     where id = d.id;

    perform public.delivery_audit(d.id, 'CONFIRMATION_FAILED', d.status, d.status,
                                  'Incorrect confirmation code (attempt ' || v_attempts || ')');

    -- Return (do not raise) so the attempt counter and audit row survive: an
    -- exception would roll the whole statement back and defeat rate limiting.
    return jsonb_build_object(
      'success', false,
      'error', case when v_attempts >= 5
                    then 'Too many incorrect attempts. Try again after the lock expires.'
                    else 'Incorrect delivery confirmation code' end,
      'attempts', v_attempts
    );
  end if;

  update public.deliveries
     set status = 'DELIVERED',
         delivered_at = coalesce(delivered_at, now()),
         confirmed_at = now(),
         confirmed_by = caller,
         confirmation_hash = null,
         confirmation_salt = null,
         confirmation_expires_at = null,
         confirmation_attempts = 0,
         confirmation_locked_until = null,
         failure_reason = '',
         updated_at = now()
   where id = d.id;

  insert into public.delivery_events (delivery_id, status, note, actor_id, actor_role)
  values (d.id, 'DELIVERED',
          'Delivery confirmed with the buyer one-time code. Escrow remains held until the buyer releases it.',
          caller, case when public.is_admin() then 'ADMIN' else 'RIDER' end);

  perform public.delivery_audit(d.id, 'DELIVERY_CONFIRMED', d.status, 'DELIVERED',
                                'One-time confirmation code accepted');

  -- NOTE: deliberately does not touch orders or escrows. GoodSale policy keeps
  -- funds in escrow until the buyer releases them.

  return jsonb_build_object('success', true, 'status', 'DELIVERED', 'confirmed_at', now());
end;
$$;

