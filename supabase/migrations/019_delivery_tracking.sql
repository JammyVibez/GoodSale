insert into public.deliveries (
  order_id, delivery_number, buyer_id, seller_id,
  pickup_address, pickup_city, pickup_state,
  delivery_address, delivery_city, delivery_state,
  delivery_method, service_type, delivery_fee, fee_snapshot,
  status, rider_id, estimated_delivery_date, created_at,
  delivered_at, cancelled_at
)
select
  o.id,
  'DLV-' || o.order_number,
  o.buyer_id,
  o.seller_id,
  coalesce(s.pickup_address, ''),
  coalesce(s.pickup_city, ''),
  coalesce(s.pickup_state, ''),
  coalesce(o.delivery_address, ''),
  coalesce(o.delivery_city, ''),
  coalesce(o.delivery_state, ''),
  coalesce(nullif(o.delivery_method, ''), 'GOODSALE_PARTNER'),
  coalesce(o.service_type, 'STANDARD'),
  coalesce(o.delivery_fee, 0),
  coalesce(o.shipping_snapshot, '{}'::jsonb),
  public.delivery_status_from_order(o.status),
  o.selected_partner_id,
  case when o.estimated_delivery_max_days is not null
       then (o.created_at::date + o.estimated_delivery_max_days) else null end,
  o.created_at,
  case when o.status = 'DELIVERED_SUCCESS' then o.updated_at else null end,
  case when o.status in ('CANCELLED', 'REFUNDED') then o.updated_at else null end
from public.orders o
left join public.seller_shipping_settings s on s.seller_id = o.seller_id
where coalesce(o.delivery_method, '') <> 'PICKUP'
on conflict (order_id) do nothing;

insert into public.delivery_events (delivery_id, status, note, actor_role)
select d.id, d.status, 'Delivery record created (backfilled from order)', 'SYSTEM'
from public.deliveries d
where not exists (select 1 from public.delivery_events e where e.delivery_id = d.id);

