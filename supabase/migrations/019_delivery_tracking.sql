-- 019_delivery_tracking.sql
-- Phase 1 delivery & tracking system.
--
-- Adds a canonical delivery record per order (separate from the existing
-- delivery_jobs dispatch/GPS layer), a timestamped event history, an admin
-- audit log, server-validated lifecycle transitions, role-based access and a
-- one-time delivery confirmation code.
--
-- Additive only: orders, escrow and the existing dispatch tables keep working.

-- ---------------------------------------------------------------------------
-- Status vocabulary
-- ---------------------------------------------------------------------------
-- AWAITING_SELLER_PREPARATION -> READY_FOR_PICKUP -> AWAITING_RIDER
-- -> RIDER_ASSIGNED -> PICKED_UP -> IN_TRANSIT -> ARRIVED_AT_HUB
-- -> OUT_FOR_DELIVERY -> DELIVERY_ATTEMPTED -> DELIVERED
-- Failure branches: FAILED_DELIVERY, RETURNED_TO_SELLER, CANCELLED.

create or replace function public.delivery_transition_allowed(p_from text, p_to text)
returns boolean
language sql
immutable
as $$
  select case
    when p_from = 'AWAITING_SELLER_PREPARATION' and p_to in ('READY_FOR_PICKUP', 'CANCELLED') then true
    when p_from = 'READY_FOR_PICKUP' and p_to in ('AWAITING_RIDER', 'RIDER_ASSIGNED', 'CANCELLED') then true
    when p_from = 'AWAITING_RIDER' and p_to in ('RIDER_ASSIGNED', 'CANCELLED') then true
    when p_from = 'RIDER_ASSIGNED' and p_to in ('PICKED_UP', 'CANCELLED') then true
    when p_from = 'PICKED_UP' and p_to in ('IN_TRANSIT', 'FAILED_DELIVERY', 'RETURNED_TO_SELLER') then true
    when p_from = 'IN_TRANSIT' and p_to in ('ARRIVED_AT_HUB', 'OUT_FOR_DELIVERY', 'DELIVERY_ATTEMPTED', 'FAILED_DELIVERY', 'RETURNED_TO_SELLER') then true
    when p_from = 'ARRIVED_AT_HUB' and p_to in ('OUT_FOR_DELIVERY', 'DELIVERY_ATTEMPTED', 'FAILED_DELIVERY', 'RETURNED_TO_SELLER') then true
    when p_from = 'OUT_FOR_DELIVERY' and p_to in ('DELIVERY_ATTEMPTED', 'FAILED_DELIVERY', 'DELIVERED') then true
    when p_from = 'DELIVERY_ATTEMPTED' and p_to in ('OUT_FOR_DELIVERY', 'FAILED_DELIVERY', 'RETURNED_TO_SELLER') then true
    when p_from = 'FAILED_DELIVERY' and p_to in ('OUT_FOR_DELIVERY', 'RETURNED_TO_SELLER', 'CANCELLED') then true
    else false
  end;
$$;

-- ---------------------------------------------------------------------------
-- Canonical delivery record
-- ---------------------------------------------------------------------------
create table if not exists public.deliveries (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  delivery_number text not null unique,
  buyer_id bigint not null references public.profiles(id) on delete cascade,
  seller_id bigint not null references public.profiles(id) on delete cascade,

  pickup_address text not null default '',
  pickup_city text not null default '',
  pickup_state text not null default '',
  delivery_address text not null default '',
  delivery_city text not null default '',
  delivery_state text not null default '',

  delivery_method text not null default 'GOODSALE_PARTNER',
  service_type text not null default 'STANDARD',
  delivery_fee numeric not null default 0 check (delivery_fee >= 0),
  -- Immutable copy of the order's server-generated shipping snapshot.
  fee_snapshot jsonb not null default '{}'::jsonb,

  status text not null default 'AWAITING_SELLER_PREPARATION' check (status in (
    'AWAITING_SELLER_PREPARATION',
    'READY_FOR_PICKUP',
    'AWAITING_RIDER',
    'RIDER_ASSIGNED',
    'PICKED_UP',
    'IN_TRANSIT',
    'ARRIVED_AT_HUB',
    'OUT_FOR_DELIVERY',
    'DELIVERY_ATTEMPTED',
    'DELIVERED',
    'FAILED_DELIVERY',
    'RETURNED_TO_SELLER',
    'CANCELLED'
  )),

  rider_id bigint references public.delivery_partners(id) on delete set null,
  courier_name text not null default '',
  tracking_number text not null default '',
  estimated_delivery_date date,

  delivery_instructions text not null default '',
  failure_reason text not null default '',
  cancellation_reason text not null default '',

  picked_up_at timestamptz,
  delivered_at timestamptz,
  returned_at timestamptz,
  cancelled_at timestamptz,

  -- One-time confirmation code: only the buyer may reveal it, only the
  -- assigned rider / admin operator may submit it. Only the hash is stored.
  confirmation_hash text,
  confirmation_salt text,
  confirmation_expires_at timestamptz,
  confirmation_attempts integer not null default 0,
  confirmation_locked_until timestamptz,
  confirmed_at timestamptz,
  confirmed_by bigint references public.profiles(id) on delete set null,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_deliveries_buyer_id on public.deliveries(buyer_id);
create index if not exists idx_deliveries_seller_id on public.deliveries(seller_id);
create index if not exists idx_deliveries_status on public.deliveries(status);
create index if not exists idx_deliveries_rider_id on public.deliveries(rider_id);
create index if not exists idx_deliveries_created_at on public.deliveries(created_at desc);
create index if not exists idx_deliveries_tracking_number on public.deliveries(tracking_number);
create index if not exists idx_deliveries_delivery_state on public.deliveries(delivery_state);

drop trigger if exists deliveries_set_updated_at on public.deliveries;
create trigger deliveries_set_updated_at
  before update on public.deliveries
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Timestamped event history
-- ---------------------------------------------------------------------------
create table if not exists public.delivery_events (
  id bigint generated by default as identity primary key,
  delivery_id bigint not null references public.deliveries(id) on delete cascade,
  status text not null,
  note text not null default '',
  actor_id bigint references public.profiles(id) on delete set null,
  actor_role text not null default 'SYSTEM',
  created_at timestamptz not null default now()
);

create index if not exists idx_delivery_events_delivery_id
  on public.delivery_events(delivery_id, created_at desc);

-- ---------------------------------------------------------------------------
-- Admin audit log
-- ---------------------------------------------------------------------------
create table if not exists public.delivery_audit_logs (
  id bigint generated by default as identity primary key,
  delivery_id bigint not null references public.deliveries(id) on delete cascade,
  actor_id bigint references public.profiles(id) on delete set null,
  actor_name text not null default '',
  actor_role text not null default '',
  action text not null,
  previous_status text,
  new_status text,
  details text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists idx_delivery_audit_logs_delivery_id
  on public.delivery_audit_logs(delivery_id, created_at desc);

alter table public.deliveries enable row level security;
alter table public.delivery_events enable row level security;
alter table public.delivery_audit_logs enable row level security;

-- ---------------------------------------------------------------------------
-- Access policies
-- ---------------------------------------------------------------------------
-- Participants (buyer, seller, assigned rider) and admins may read a delivery.
drop policy if exists deliveries_participants_read on public.deliveries;
create policy deliveries_participants_read on public.deliveries
  for select to authenticated
  using (
    public.is_admin()
    or buyer_id = public.current_profile_id()
    or seller_id = public.current_profile_id()
    or exists (
      select 1 from public.delivery_partners dp
      where dp.id = deliveries.rider_id
        and dp.user_id = public.current_profile_id()
    )
  );

drop policy if exists delivery_events_participants_read on public.delivery_events;
create policy delivery_events_participants_read on public.delivery_events
  for select to authenticated
  using (
    exists (
      select 1 from public.deliveries d
      where d.id = delivery_events.delivery_id
        and (
          public.is_admin()
          or d.buyer_id = public.current_profile_id()
          or d.seller_id = public.current_profile_id()
          or exists (
            select 1 from public.delivery_partners dp
            where dp.id = d.rider_id
              and dp.user_id = public.current_profile_id()
          )
        )
    )
  );

drop policy if exists delivery_audit_admin_read on public.delivery_audit_logs;
create policy delivery_audit_admin_read on public.delivery_audit_logs
  for select to authenticated
  using (public.is_admin());

-- Status changes never happen through table writes: only the SECURITY DEFINER
-- functions below may update a delivery, so no insert/update policies exist.

-- ---------------------------------------------------------------------------
-- Order -> delivery creation
-- ---------------------------------------------------------------------------
create or replace function public.delivery_status_from_order(p_status text)
returns text
language sql
immutable
as $$
  select case
    when p_status in ('DELIVERED_SUCCESS') then 'DELIVERED'
    when p_status in ('SHIPPED') then 'IN_TRANSIT'
    when p_status in ('OUT_FOR_DELIVERY') then 'OUT_FOR_DELIVERY'
    when p_status in ('CANCELLED', 'REFUNDED') then 'CANCELLED'
    else 'AWAITING_SELLER_PREPARATION'
  end;
$$;

create or replace function public.create_delivery_for_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pickup record;
  v_delivery_id bigint;
  v_status text;
  v_eta date;
begin
  -- Self-pickup orders do not need a coordinated delivery record.
  if coalesce(new.delivery_method, '') = 'PICKUP' then
    return new;
  end if;

  select pickup_address, pickup_city, pickup_state
    into v_pickup
  from public.seller_shipping_settings
  where seller_id = new.seller_id;

  v_status := public.delivery_status_from_order(new.status);

  v_eta := case
    when new.estimated_delivery_max_days is not null
      then (new.created_at::date + new.estimated_delivery_max_days)
    else null
  end;

  insert into public.deliveries (
    order_id, delivery_number, buyer_id, seller_id,
    pickup_address, pickup_city, pickup_state,
    delivery_address, delivery_city, delivery_state,
    delivery_method, service_type, delivery_fee, fee_snapshot,
    status, rider_id, estimated_delivery_date, created_at
  ) values (
    new.id,
    'DLV-' || new.order_number,
    new.buyer_id,
    new.seller_id,
    coalesce(v_pickup.pickup_address, ''),
    coalesce(v_pickup.pickup_city, ''),
    coalesce(v_pickup.pickup_state, ''),
    coalesce(new.delivery_address, ''),
    coalesce(new.delivery_city, ''),
    coalesce(new.delivery_state, ''),
    coalesce(nullif(new.delivery_method, ''), 'GOODSALE_PARTNER'),
    coalesce(new.service_type, 'STANDARD'),
    coalesce(new.delivery_fee, 0),
    coalesce(new.shipping_snapshot, '{}'::jsonb),
    v_status,
    new.selected_partner_id,
    v_eta,
    new.created_at
  )
  on conflict (order_id) do nothing
  returning id into v_delivery_id;

  if v_delivery_id is not null then
    insert into public.delivery_events (delivery_id, status, note, actor_role)
    values (v_delivery_id, v_status, 'Delivery record created with the order', 'SYSTEM');
  end if;

  return new;
end;
$$;

drop trigger if exists orders_create_delivery on public.orders;
create trigger orders_create_delivery
  after insert on public.orders
  for each row execute function public.create_delivery_for_order();

-- Keep the canonical delivery in step with the existing order lifecycle.
-- Escrow release (buyer PIN) sets DELIVERED_SUCCESS -> delivery DELIVERED.
create or replace function public.sync_delivery_with_order_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  if new.status is not distinct from old.status then
    return new;
  end if;

  if new.status = 'DELIVERED_SUCCESS' then
    update public.deliveries
       set status = 'DELIVERED',
           delivered_at = coalesce(delivered_at, now()),
           confirmed_at = coalesce(confirmed_at, now())
     where order_id = new.id
       and status not in ('DELIVERED', 'RETURNED_TO_SELLER', 'CANCELLED')
    returning id into v_id;

    if v_id is not null then
      insert into public.delivery_events (delivery_id, status, note, actor_role)
      values (v_id, 'DELIVERED', 'Buyer confirmed delivery and released escrow', 'SYSTEM');
    end if;

  elsif new.status = 'SHIPPED' then
    update public.deliveries
       set status = 'IN_TRANSIT',
           picked_up_at = coalesce(picked_up_at, now())
     where order_id = new.id
       and status in ('AWAITING_SELLER_PREPARATION', 'READY_FOR_PICKUP', 'AWAITING_RIDER', 'RIDER_ASSIGNED', 'PICKED_UP')
    returning id into v_id;

    if v_id is not null then
      insert into public.delivery_events (delivery_id, status, note, actor_role)
      values (v_id, 'IN_TRANSIT', 'Seller dispatched the package (order marked shipped)', 'SYSTEM');
    end if;

  elsif new.status = 'OUT_FOR_DELIVERY' then
    update public.deliveries
       set status = 'OUT_FOR_DELIVERY'
     where order_id = new.id
       and status in ('AWAITING_SELLER_PREPARATION', 'READY_FOR_PICKUP', 'AWAITING_RIDER', 'RIDER_ASSIGNED', 'PICKED_UP', 'IN_TRANSIT', 'ARRIVED_AT_HUB')
    returning id into v_id;

    if v_id is not null then
      insert into public.delivery_events (delivery_id, status, note, actor_role)
      values (v_id, 'OUT_FOR_DELIVERY', 'Package is out for delivery', 'SYSTEM');
    end if;

  elsif new.status in ('CANCELLED', 'REFUNDED') then
    update public.deliveries
       set status = 'CANCELLED',
           cancelled_at = coalesce(cancelled_at, now()),
           cancellation_reason = coalesce(nullif(cancellation_reason, ''), 'Order cancelled')
     where order_id = new.id
       and status not in ('DELIVERED', 'RETURNED_TO_SELLER', 'CANCELLED')
    returning id into v_id;

    update public.delivery_jobs
       set status = 'CANCELLED', updated_at = now()
     where order_id = new.id and status not in ('COMPLETED', 'CANCELLED');

    if v_id is not null then
      insert into public.delivery_events (delivery_id, status, note, actor_role)
      values (v_id, 'CANCELLED', 'Order was cancelled', 'SYSTEM');
    end if;

  elsif new.status = 'DISPUTED' then
    update public.deliveries set updated_at = now() where order_id = new.id returning id into v_id;
    if v_id is not null then
      insert into public.delivery_events (delivery_id, status, note, actor_role)
      values (v_id, (select status from public.deliveries where id = v_id),
              'Buyer opened a dispute — delivery funds stay protected', 'SYSTEM');
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists orders_sync_delivery_status on public.orders;
create trigger orders_sync_delivery_status
  after update of status on public.orders
  for each row execute function public.sync_delivery_with_order_status();

-- ---------------------------------------------------------------------------
-- Shared helpers
-- ---------------------------------------------------------------------------
create or replace function public.delivery_audit(
  p_delivery_id bigint,
  p_action text,
  p_previous_status text,
  p_new_status text,
  p_details text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_caller bigint := public.current_profile_id();
  v_name text := '';
  v_role text := '';
begin
  if v_caller is not null then
    select full_name, role into v_name, v_role
    from public.profiles where id = v_caller;
  end if;

  insert into public.delivery_audit_logs (
    delivery_id, actor_id, actor_name, actor_role, action,
    previous_status, new_status, details
  ) values (
    p_delivery_id, v_caller, coalesce(v_name, ''), coalesce(v_role, 'SYSTEM'),
    p_action, p_previous_status, p_new_status, coalesce(p_details, '')
  );
end;
$$;

-- Internal: role of the caller for a given delivery row.
create or replace function public.delivery_caller_is_rider(p_delivery public.deliveries)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.delivery_partners dp
    where dp.id = p_delivery.rider_id
      and dp.user_id = public.current_profile_id()
  );
$$;

-- ---------------------------------------------------------------------------
-- Seller actions (availability / preparing / ready)
-- ---------------------------------------------------------------------------
create or replace function public.delivery_seller_action(p_delivery_id bigint, p_action text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  d public.deliveries%ROWTYPE;
  caller bigint := public.current_profile_id();
  v_action text := upper(coalesce(p_action, ''));
  v_status text;
  v_note text;
begin
  if caller is null then
    raise exception 'Not authenticated';
  end if;

  select * into d from public.deliveries where id = p_delivery_id for update;
  if not found then
    raise exception 'Delivery not found';
  end if;

  if d.seller_id <> caller and not public.is_admin() then
    raise exception 'Only the seller can update preparation status';
  end if;

  if d.status in ('DELIVERED', 'CANCELLED', 'RETURNED_TO_SELLER') then
    raise exception 'Delivery is closed';
  end if;

  if d.status not in ('AWAITING_SELLER_PREPARATION', 'READY_FOR_PICKUP') and v_action <> 'CONFIRM_AVAILABILITY' then
    raise exception 'Preparation is already complete';
  end if;

  if v_action = 'CONFIRM_AVAILABILITY' then
    v_status := d.status;
    v_note := 'Seller confirmed the item is available and in stock';
  elsif v_action = 'PREPARING' then
    v_status := d.status;
    v_note := 'Seller is preparing the item for pickup';
  elsif v_action = 'READY_FOR_PICKUP' then
    if d.status = 'READY_FOR_PICKUP' then
      raise exception 'Item is already marked ready for pickup';
    end if;
    v_status := 'READY_FOR_PICKUP';
    v_note := 'Seller marked the item ready for pickup';
  else
    raise exception 'Unknown seller action';
  end if;

  if v_status <> d.status then
    update public.deliveries
       set status = v_status, updated_at = now()
     where id = d.id;
  end if;

  insert into public.delivery_events (delivery_id, status, note, actor_id, actor_role)
  values (d.id, v_status, v_note, caller,
          case when public.is_admin() then 'ADMIN' else 'SELLER' end);

  perform public.delivery_audit(d.id, 'SELLER_' || v_action, d.status, v_status, v_note);

  return jsonb_build_object('success', true, 'status', v_status, 'note', v_note);
end;
$$;

-- ---------------------------------------------------------------------------
-- Lifecycle transitions (seller / rider / admin, validated server-side)
-- ---------------------------------------------------------------------------
create or replace function public.delivery_transition(
  p_delivery_id bigint,
  p_status text,
  p_note text default null,
  p_failure_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  d public.deliveries%ROWTYPE;
  caller bigint := public.current_profile_id();
  v_to text := upper(coalesce(p_status, ''));
  v_is_rider boolean;
  v_is_seller boolean;
  v_allowed boolean := false;
  v_note text := coalesce(nullif(p_note, ''), '');
begin
  if caller is null then
    raise exception 'Not authenticated';
  end if;

  select * into d from public.deliveries where id = p_delivery_id for update;
  if not found then
    raise exception 'Delivery not found';
  end if;

  if v_to = 'DELIVERED' then
    raise exception 'Delivery must be confirmed with the buyer confirmation code';
  end if;

  if not public.delivery_transition_allowed(d.status, v_to) then
    raise exception 'Cannot move delivery from % to %', d.status, v_to;
  end if;

  v_is_seller := d.seller_id = caller;
  v_is_rider := public.delivery_caller_is_rider(d);

  if public.is_admin() then
    -- Admins may correct any non-terminal state, but cannot force DELIVERED.
    v_allowed := true;
  elsif v_is_seller then
    v_allowed := d.status = 'AWAITING_SELLER_PREPARATION' and v_to = 'READY_FOR_PICKUP';
  elsif v_is_rider then
    v_allowed := (d.status, v_to) in (
      ('RIDER_ASSIGNED', 'PICKED_UP'),
      ('PICKED_UP', 'IN_TRANSIT'),
      ('PICKED_UP', 'FAILED_DELIVERY'),
      ('IN_TRANSIT', 'ARRIVED_AT_HUB'),
      ('IN_TRANSIT', 'OUT_FOR_DELIVERY'),
      ('IN_TRANSIT', 'DELIVERY_ATTEMPTED'),
      ('IN_TRANSIT', 'FAILED_DELIVERY'),
      ('ARRIVED_AT_HUB', 'OUT_FOR_DELIVERY'),
      ('ARRIVED_AT_HUB', 'DELIVERY_ATTEMPTED'),
      ('ARRIVED_AT_HUB', 'FAILED_DELIVERY'),
      ('OUT_FOR_DELIVERY', 'DELIVERY_ATTEMPTED'),
      ('OUT_FOR_DELIVERY', 'FAILED_DELIVERY'),
      ('DELIVERY_ATTEMPTED', 'OUT_FOR_DELIVERY'),
      ('DELIVERY_ATTEMPTED', 'FAILED_DELIVERY')
    );
  end if;

  if not v_allowed then
    raise exception 'Your role cannot perform this delivery update';
  end if;

  if v_to = 'FAILED_DELIVERY' and coalesce(nullif(p_failure_reason, ''), '') = '' then
    raise exception 'A failure reason is required';
  end if;

  update public.deliveries
     set status = v_to,
         failure_reason = case
           when v_to = 'FAILED_DELIVERY' then coalesce(nullif(p_failure_reason, ''), failure_reason)
           when v_to in ('OUT_FOR_DELIVERY', 'DELIVERED') then ''
           else failure_reason
         end,
         picked_up_at = case when v_to = 'PICKED_UP' then coalesce(picked_up_at, now()) else picked_up_at end,
         delivered_at = case when v_to = 'DELIVERED' then coalesce(delivered_at, now()) else delivered_at end,
         returned_at = case when v_to = 'RETURNED_TO_SELLER' then coalesce(returned_at, now()) else returned_at end,
         cancelled_at = case when v_to = 'CANCELLED' then coalesce(cancelled_at, now()) else cancelled_at end,
         updated_at = now()
   where id = d.id;

  if v_note = '' then
    v_note := 'Delivery status updated to ' || replace(v_to, '_', ' ');
  end if;

  insert into public.delivery_events (delivery_id, status, note, actor_id, actor_role)
  values (d.id, v_to, v_note, caller,
          case
            when public.is_admin() then 'ADMIN'
            when v_is_rider then 'RIDER'
            when v_is_seller then 'SELLER'
            else 'SYSTEM'
          end);

  perform public.delivery_audit(d.id, 'STATUS_' || v_to, d.status, v_to, v_note);

  -- A cancellation should also stop the legacy dispatch job if one is open.
  if v_to = 'CANCELLED' then
    update public.delivery_jobs
       set status = 'CANCELLED', updated_at = now()
     where order_id = d.order_id and status not in ('COMPLETED', 'CANCELLED');
  end if;

  return jsonb_build_object('success', true, 'previous_status', d.status, 'status', v_to);
end;
$$;

-- ---------------------------------------------------------------------------
-- Admin: rider assignment / courier / tracking number
-- ---------------------------------------------------------------------------
create or replace function public.delivery_assign_rider(p_delivery_id bigint, p_rider_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  d public.deliveries%ROWTYPE;
  p public.delivery_partners%ROWTYPE;
  v_status text;
begin
  if not public.is_admin() then
    raise exception 'Admins only';
  end if;

  select * into d from public.deliveries where id = p_delivery_id for update;
  if not found then
    raise exception 'Delivery not found';
  end if;
  if d.status in ('DELIVERED', 'CANCELLED', 'RETURNED_TO_SELLER') then
    raise exception 'Delivery is closed';
  end if;

  select * into p from public.delivery_partners where id = p_rider_id;
  if not found then
    raise exception 'Rider not found';
  end if;
  if p.status <> 'APPROVED' then
    raise exception 'Rider is not approved yet';
  end if;

  v_status := case
    when d.status in ('AWAITING_SELLER_PREPARATION', 'READY_FOR_PICKUP', 'AWAITING_RIDER', 'RIDER_ASSIGNED')
      then 'RIDER_ASSIGNED'
    else d.status
  end;

  update public.deliveries
     set rider_id = p.id,
         courier_name = case when coalesce(courier_name, '') = '' then p.full_name else courier_name end,
         status = v_status,
         updated_at = now()
   where id = d.id;

  -- Keep the dispatch layer in step so live tracking shows the same rider.
  update public.delivery_jobs
     set partner_id = p.id, updated_at = now()
   where order_id = d.order_id and status not in ('COMPLETED', 'CANCELLED');

  insert into public.delivery_events (delivery_id, status, note, actor_id, actor_role)
  values (d.id, v_status, 'Rider ' || p.full_name || ' assigned by admin',
          public.current_profile_id(), 'ADMIN');

  perform public.delivery_audit(
    d.id, 'ASSIGN_RIDER', d.status, v_status,
    'Rider #' || p.id || ' (' || p.full_name || ', ' || p.vehicle_type || ') assigned'
  );

  return jsonb_build_object('success', true, 'status', v_status, 'rider_id', p.id);
end;
$$;

create or replace function public.delivery_set_courier(
  p_delivery_id bigint,
  p_courier_name text,
  p_tracking_number text,
  p_estimated_delivery_date date default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  d public.deliveries%ROWTYPE;
  v_status text;
  v_courier text := btrim(coalesce(p_courier_name, ''));
begin
  if not public.is_admin() then
    raise exception 'Admins only';
  end if;

  select * into d from public.deliveries where id = p_delivery_id for update;
  if not found then
    raise exception 'Delivery not found';
  end if;
  if d.status in ('DELIVERED', 'CANCELLED', 'RETURNED_TO_SELLER') then
