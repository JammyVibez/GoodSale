  values (d.id, v_status,
          'Courier ' || v_courier ||
          case when coalesce(p_tracking_number, '') <> '' then ' · tracking ' || btrim(p_tracking_number) else '' end,
          public.current_profile_id(), 'ADMIN');

  perform public.delivery_audit(
    d.id, 'SET_COURIER', d.status, v_status,
    'Courier ' || v_courier || coalesce(' · tracking ' || nullif(btrim(coalesce(p_tracking_number, '')), ''), '')
  );

  return jsonb_build_object('success', true, 'status', v_status);
end;
$$;

