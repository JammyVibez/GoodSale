create or replace function public.delivery_cancel(p_delivery_id bigint, p_reason text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  d public.deliveries%ROWTYPE;
  v_reason text := btrim(coalesce(p_reason, ''));
begin
  if not public.is_admin() then
