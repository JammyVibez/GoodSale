  end if;
  if v_reason = '' then
    raise exception 'A return reason is required';
  end if;

  update public.deliveries
     set status = 'RETURNED_TO_SELLER',
         failure_reason = v_reason,
         returned_at = now(),
         updated_at = now()
   where id = d.id;

  insert into public.delivery_events (delivery_id, status, note, actor_id, actor_role)
  values (d.id, 'RETURNED_TO_SELLER', 'Return initiated: ' || v_reason, public.current_profile_id(), 'ADMIN');

  perform public.delivery_audit(d.id, 'RETURN_TO_SELLER', d.status, 'RETURNED_TO_SELLER', v_reason);

  return jsonb_build_object('success', true, 'status', 'RETURNED_TO_SELLER');
end;
$$;

