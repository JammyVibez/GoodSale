create or replace function public.delivery_initiate_return(p_delivery_id bigint, p_reason text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  d public.deliveries%ROWTYPE;
  v_reason text := btrim(coalesce(p_reason, ''));
begin
  if not public.is_admin() then
    raise exception 'Admins only';
  end if;

  select * into d from public.deliveries where id = p_delivery_id for update;
  if not found then
    raise exception 'Delivery not found';
  end if;
  if d.status not in ('FAILED_DELIVERY', 'DELIVERY_ATTEMPTED', 'IN_TRANSIT', 'ARRIVED_AT_HUB', 'OUT_FOR_DELIVERY', 'PICKED_UP') then
