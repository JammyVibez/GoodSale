-- 020_rider_management.sql
-- Phase 2: dedicated Rider accounts, verification, assignment/acceptance,
-- rider workflow events, earnings and admin rider management.
--
-- Builds on 019_delivery_tracking.sql. The existing delivery_jobs table stays
-- as the live-GPS/dispatch layer; `deliveries` remains the canonical record.

-- ---------------------------------------------------------------------------
-- 1. RIDER role
-- ---------------------------------------------------------------------------
-- BUYER -> RIDER is allowed only through the rider_apply() function (guarded by
-- a transaction-local flag). RIDER -> BUYER is allowed so a rider can leave the
-- programme. Nothing else changes role automatically.
CREATE OR REPLACE FUNCTION public.protect_profile_sensitive_columns()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    IF NEW.role IS DISTINCT FROM OLD.role
       AND NOT (
         OLD.role IN ('BUYER', 'SELLER', 'BUSINESS')
         AND NEW.role IN ('BUYER', 'SELLER', 'BUSINESS')
       )
       AND NOT (
         OLD.role = 'BUYER'
         AND NEW.role = 'RIDER'
         AND coalesce(current_setting('goodsale.rider_registration', true), '') = 'on'
       )
       AND NOT (OLD.role = 'RIDER' AND NEW.role = 'BUYER')
    THEN
      RAISE EXCEPTION 'Updating role is not allowed';
    END IF;
    IF NEW.good_points IS DISTINCT FROM OLD.good_points THEN
      RAISE EXCEPTION 'Updating good_points is not allowed';
    END IF;
    IF NEW.trust_score IS DISTINCT FROM OLD.trust_score THEN
      RAISE EXCEPTION 'Updating trust_score is not allowed';
    END IF;
    IF NEW.seller_level IS DISTINCT FROM OLD.seller_level THEN
      RAISE EXCEPTION 'Updating seller_level is not allowed';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_set_profile_role(p_user_id bigint, p_role text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Admin only';
  END IF;
  IF p_role NOT IN (
    'BUYER','SELLER','VERIFIED_SELLER','BUSINESS','VERIFIED_BUSINESS','RIDER','MODERATOR','ADMIN','SUPER_ADMIN'
  ) THEN
    RAISE EXCEPTION 'Invalid role';
  END IF;
  UPDATE public.profiles SET role = p_role WHERE id = p_user_id;
END;
$$;

