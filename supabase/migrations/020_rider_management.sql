)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  p public.delivery_partners%ROWTYPE;
  v_status text := upper(coalesce(p_status, ''));
  v_reason text := btrim(coalesce(p_reason, ''));
  v_admin bigint := public.current_profile_id();
  v_admin_name text;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Admins only';
  END IF;
  IF v_status NOT IN ('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED') THEN
    RAISE EXCEPTION 'Invalid rider status';
  END IF;
  IF v_status IN ('REJECTED', 'SUSPENDED') AND v_reason = '' THEN
    RAISE EXCEPTION 'A reason is required to reject or suspend a rider';
  END IF;

  SELECT * INTO p FROM public.delivery_partners WHERE id = p_rider_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Rider not found';
  END IF;

  IF v_status = 'SUSPENDED' AND EXISTS (
    SELECT 1 FROM public.deliveries
    WHERE rider_id = p.id
      AND status IN ('PICKED_UP', 'IN_TRANSIT', 'ARRIVED_AT_HUB', 'OUT_FOR_DELIVERY', 'DELIVERY_ATTEMPTED')
  ) THEN
    RAISE EXCEPTION 'Reassign this rider''s in-progress deliveries before suspending them';
  END IF;

  PERFORM set_config('goodsale.rider_system', 'on', true);

  UPDATE public.delivery_partners
     SET status = v_status,
         is_available = CASE WHEN v_status = 'APPROVED' THEN is_available ELSE false END,
         rejection_reason = CASE WHEN v_status = 'REJECTED' THEN v_reason ELSE '' END,
         suspension_reason = CASE WHEN v_status = 'SUSPENDED' THEN v_reason ELSE '' END,
         suspended_at = CASE WHEN v_status = 'SUSPENDED' THEN now() ELSE NULL END,
         reviewed_by = v_admin,
         reviewed_at = now(),
         updated_at = now()
   WHERE id = p.id;

  IF v_status = 'APPROVED' THEN
    UPDATE public.profiles SET role = 'RIDER', updated_at = now()
    WHERE id = p.user_id AND role NOT IN ('ADMIN', 'SUPER_ADMIN', 'MODERATOR', 'SELLER', 'VERIFIED_SELLER', 'BUSINESS', 'VERIFIED_BUSINESS');
  END IF;

  -- Suspension/rejection releases any uncollected assignments.
  IF v_status <> 'APPROVED' THEN
    UPDATE public.deliveries
       SET rider_id = NULL,
           assignment_status = 'REJECTED',
           assignment_offered_at = NULL,
           assignment_expires_at = NULL,
           status = 'AWAITING_RIDER',
           updated_at = now()
     WHERE rider_id = p.id
       AND status IN ('RIDER_ASSIGNED', 'READY_FOR_PICKUP', 'AWAITING_RIDER');

    UPDATE public.delivery_jobs
       SET partner_id = NULL, updated_at = now()
     WHERE partner_id = p.id AND status NOT IN ('COMPLETED', 'CANCELLED');
  END IF;

  SELECT full_name INTO v_admin_name FROM public.profiles WHERE id = v_admin;

  INSERT INTO public.audit_logs (user_id, action, entity_type, entity_id, details)
  VALUES (v_admin, 'RIDER_' || v_status, 'delivery_partners', p.id,
          'Rider ' || p.full_name || coalesce(' — ' || nullif(v_reason, ''), ''));

  INSERT INTO public.notifications (user_id, title, message, type)
  VALUES (
    p.user_id,
    CASE v_status
      WHEN 'APPROVED' THEN 'Rider account approved'
      WHEN 'REJECTED' THEN 'Rider application rejected'
      WHEN 'SUSPENDED' THEN 'Rider account suspended'
      ELSE 'Rider application under review'
    END,
    CASE v_status
      WHEN 'APPROVED' THEN 'Your rider account is approved. Go online to receive delivery requests.'
      WHEN 'REJECTED' THEN 'Your rider application was rejected.' || coalesce(' Reason: ' || nullif(v_reason, ''), '')
      WHEN 'SUSPENDED' THEN 'Your rider account was suspended.' || coalesce(' Reason: ' || nullif(v_reason, ''), '')
      ELSE 'Your rider application is under review.'
    END,
    'VERIFICATION'
  );

  PERFORM set_config('goodsale.rider_system', 'off', true);
  RETURN jsonb_build_object('success', true, 'status', v_status);
END;
$$;

