-- ---------------------------------------------------------------------------
-- 7. Column guards
-- ---------------------------------------------------------------------------
-- Riders may edit availability/location via their RPC, never verification,
-- commission or review fields.
CREATE OR REPLACE FUNCTION public.protect_rider_sensitive_columns()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF public.is_admin()
     OR coalesce(current_setting('goodsale.rider_system', true), '') = 'on'
     OR coalesce(current_setting('goodsale.rider_registration', true), '') = 'on' THEN
    RETURN NEW;
  END IF;

  IF NEW.user_id IS DISTINCT FROM OLD.user_id
     OR NEW.status IS DISTINCT FROM OLD.status
     OR NEW.reviewed_by IS DISTINCT FROM OLD.reviewed_by
     OR NEW.reviewed_at IS DISTINCT FROM OLD.reviewed_at
     OR NEW.rejection_reason IS DISTINCT FROM OLD.rejection_reason
     OR NEW.suspension_reason IS DISTINCT FROM OLD.suspension_reason
     OR NEW.suspended_at IS DISTINCT FROM OLD.suspended_at
     OR NEW.nin IS DISTINCT FROM OLD.nin
     OR NEW.documents IS DISTINCT FROM OLD.documents
     OR NEW.selfie_url IS DISTINCT FROM OLD.selfie_url
     OR NEW.license_url IS DISTINCT FROM OLD.license_url
     OR NEW.commission_percentage IS DISTINCT FROM OLD.commission_percentage
     OR NEW.trust_score IS DISTINCT FROM OLD.trust_score
     OR NEW.completed_deliveries IS DISTINCT FROM OLD.completed_deliveries
     OR NEW.acceptance_rate IS DISTINCT FROM OLD.acceptance_rate
  THEN
    RAISE EXCEPTION 'Rider verification fields can only be changed by GoodSale';
  END IF;

  IF OLD.status = 'SUSPENDED' AND NEW.is_available = true THEN
    RAISE EXCEPTION 'Suspended riders cannot go online';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS delivery_partners_protect_sensitive ON public.delivery_partners;
CREATE TRIGGER delivery_partners_protect_sensitive
  BEFORE UPDATE ON public.delivery_partners
  FOR EACH ROW EXECUTE FUNCTION public.protect_rider_sensitive_columns();

-- A rider may only change a delivery they accepted, and only while approved.
CREATE OR REPLACE FUNCTION public.enforce_rider_delivery_access()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_status text;
BEGIN
  IF public.is_admin()
     OR coalesce(current_setting('goodsale.rider_system', true), '') = 'on' THEN
    RETURN NEW;
  END IF;

  SELECT status INTO v_status
  FROM public.delivery_partners
  WHERE id = OLD.rider_id AND user_id = public.current_profile_id();

  IF FOUND THEN
    IF v_status <> 'APPROVED' THEN
      RAISE EXCEPTION 'Rider account is not active';
    END IF;
    -- Accepting an offered assignment is the one pre-acceptance write allowed.
    IF OLD.assignment_status = 'OFFERED'
       AND NEW.assignment_status = 'ACCEPTED'
       AND NEW.rider_id = OLD.rider_id THEN
      RETURN NEW;
    END IF;
    IF OLD.assignment_status <> 'ACCEPTED' THEN
      RAISE EXCEPTION 'Delivery assignment has not been accepted';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS deliveries_enforce_rider_access ON public.deliveries;
CREATE TRIGGER deliveries_enforce_rider_access
  BEFORE UPDATE ON public.deliveries
  FOR EACH ROW EXECUTE FUNCTION public.enforce_rider_delivery_access();

-- ---------------------------------------------------------------------------
-- 8. Rider application
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.rider_apply(p_payload jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  caller bigint := public.current_profile_id();
  p public.delivery_partners%ROWTYPE;
  v_profile public.profiles%ROWTYPE;
  v_vehicle text := upper(coalesce(p_payload->>'vehicle_type', 'MOTORCYCLE'));
  v_documents jsonb := coalesce(p_payload->'documents', '[]'::jsonb);
  v_states text[] := coalesce(
    (SELECT array_agg(value) FROM jsonb_array_elements_text(coalesce(p_payload->'service_states', '[]'::jsonb)) AS value),
    '{}'
  );
  v_status text;
  v_exists boolean;
BEGIN
  IF caller IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  SELECT * INTO v_profile FROM public.profiles WHERE id = caller FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Profile not found';
  END IF;
  IF v_profile.role IN ('ADMIN', 'SUPER_ADMIN', 'MODERATOR', 'SELLER', 'VERIFIED_SELLER', 'BUSINESS', 'VERIFIED_BUSINESS') THEN
    RAISE EXCEPTION 'Rider accounts must use a separate buyer account';
  END IF;

  IF coalesce(p_payload->>'full_name', '') = ''
     OR coalesce(p_payload->>'phone', '') = ''
     OR coalesce(p_payload->>'state', '') = ''
     OR coalesce(p_payload->>'city', '') = '' THEN
    RAISE EXCEPTION 'Name, phone, state and operating city are required';
  END IF;
  IF coalesce(p_payload->>'nin', '') = '' AND jsonb_array_length(v_documents) = 0 THEN
    RAISE EXCEPTION 'A government ID or uploaded identification document is required';
  END IF;

  SELECT * INTO p FROM public.delivery_partners WHERE user_id = caller FOR UPDATE;
  v_exists := FOUND;
  IF v_exists AND p.status = 'APPROVED' THEN
    RAISE EXCEPTION 'You are already an approved rider';
  END IF;
  IF v_exists AND p.status = 'SUSPENDED' THEN
    RAISE EXCEPTION 'Your rider account is suspended. Contact support.';
  END IF;

  PERFORM set_config('goodsale.rider_registration', 'on', true);
  PERFORM set_config('goodsale.rider_system', 'on', true);

  IF v_exists THEN
    v_status := 'PENDING';
    UPDATE public.delivery_partners
       SET full_name = p_payload->>'full_name',
           phone = p_payload->>'phone',
           email = coalesce(p_payload->>'email', ''),
           vehicle_type = v_vehicle,
           brand = coalesce(p_payload->>'brand', ''),
           model = coalesce(p_payload->>'model', ''),
           plate_number = coalesce(p_payload->>'plate_number', ''),
           color = coalesce(p_payload->>'color', ''),
           year = nullif(p_payload->>'year', '')::int,
           capacity = coalesce(p_payload->>'capacity', ''),
           photo_url = coalesce(p_payload->>'photo_url', ''),
           address = coalesce(p_payload->>'address', ''),
           state = p_payload->>'state',
           city = p_payload->>'city',
           nin = coalesce(p_payload->>'nin', ''),
           selfie_url = coalesce(p_payload->>'selfie_url', ''),
           license_url = nullif(p_payload->>'license_url', ''),
           documents = v_documents,
           emergency_contact_name = coalesce(p_payload->>'emergency_contact_name', ''),
           emergency_contact_phone = coalesce(p_payload->>'emergency_contact_phone', ''),
           emergency_contact_relation = coalesce(p_payload->>'emergency_contact_relation', ''),
           service_states = v_states,
           status = 'PENDING',
           is_available = false,
           rejection_reason = '',
           reviewed_by = null,
           reviewed_at = null,
           updated_at = now()
     WHERE id = p.id;
  ELSE
    v_status := 'PENDING';
    INSERT INTO public.delivery_partners (
      user_id, full_name, phone, email, vehicle_type, brand, model, plate_number,
      color, year, capacity, photo_url, status, is_available, address, state, city,
      nin, selfie_url, license_url, documents,
      emergency_contact_name, emergency_contact_phone, emergency_contact_relation,
      service_states
    ) VALUES (
      caller, p_payload->>'full_name', p_payload->>'phone', coalesce(p_payload->>'email', ''),
      v_vehicle, coalesce(p_payload->>'brand', ''), coalesce(p_payload->>'model', ''),
      coalesce(p_payload->>'plate_number', ''), coalesce(p_payload->>'color', ''),
      nullif(p_payload->>'year', '')::int, coalesce(p_payload->>'capacity', ''),
      coalesce(p_payload->>'photo_url', ''), 'PENDING', false,
      coalesce(p_payload->>'address', ''), p_payload->>'state', p_payload->>'city',
      coalesce(p_payload->>'nin', ''), coalesce(p_payload->>'selfie_url', ''),
      nullif(p_payload->>'license_url', ''), v_documents,
      coalesce(p_payload->>'emergency_contact_name', ''),
      coalesce(p_payload->>'emergency_contact_phone', ''),
      coalesce(p_payload->>'emergency_contact_relation', ''),
      v_states
    );
  END IF;

  UPDATE public.profiles SET role = 'RIDER', updated_at = now() WHERE id = caller;

  INSERT INTO public.notifications (user_id, title, message, type)
  VALUES (caller, 'Rider application submitted', 'Your GoodDispatch rider application is under review. You can go online once approved.', 'VERIFICATION');

  INSERT INTO public.audit_logs (user_id, action, entity_type, entity_id, details)
  SELECT caller, 'RIDER_APPLICATION_SUBMITTED', 'delivery_partners', id,
         'Rider application submitted for ' || vehicle_type || ' in ' || city || ', ' || state
  FROM public.delivery_partners WHERE user_id = caller;

  SELECT * INTO p FROM public.delivery_partners WHERE user_id = caller;
  PERFORM set_config('goodsale.rider_system', 'off', true);
  PERFORM set_config('goodsale.rider_registration', 'off', true);
  RETURN jsonb_build_object('success', true, 'rider_id', p.id, 'status', v_status);
END;
$$;

-- ---------------------------------------------------------------------------
-- 9. Availability and profile
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.rider_update_availability(
  p_online boolean,
  p_lat double precision DEFAULT NULL,
  p_lng double precision DEFAULT NULL,
  p_state text DEFAULT NULL,
  p_city text DEFAULT NULL,
  p_service_states text[] DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  p public.delivery_partners%ROWTYPE;
  caller bigint := public.current_profile_id();
BEGIN
  IF caller IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;
  SELECT * INTO p FROM public.delivery_partners WHERE user_id = caller FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Rider profile not found';
  END IF;
  IF p.status <> 'APPROVED' THEN
    RAISE EXCEPTION 'Only approved riders can change availability';
  END IF;

  PERFORM set_config('goodsale.rider_system', 'on', true);

  UPDATE public.delivery_partners
     SET is_available = p_online,
         last_lat = coalesce(p_lat, last_lat),
         last_lng = coalesce(p_lng, last_lng),
         last_location_at = case when p_lat is not null and p_lng is not null then now() else last_location_at end,
         last_seen_at = now(),
         state = coalesce(nullif(p_state, ''), state),
         city = coalesce(nullif(p_city, ''), city),
         service_states = coalesce(p_service_states, service_states),
         updated_at = now()
   WHERE id = p.id;

  INSERT INTO public.audit_logs (user_id, action, entity_type, entity_id, details)
  VALUES (caller, case when p_online then 'RIDER_WENT_ONLINE' else 'RIDER_WENT_OFFLINE' end,
          'delivery_partners', p.id,
          case when p_online then 'Rider is available for delivery requests' else 'Rider stopped receiving requests' end);

  PERFORM set_config('goodsale.rider_system', 'off', true);
  RETURN jsonb_build_object('success', true, 'is_available', p_online);
END;
$$;

-- ---------------------------------------------------------------------------
-- 10. Assignment expiry, available requests, accept / reject
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.expire_rider_assignments()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row record;
  v_user bigint;
  v_count integer := 0;
BEGIN
  PERFORM set_config('goodsale.rider_system', 'on', true);

  FOR v_row IN
    SELECT d.id, d.rider_id, d.order_id, d.delivery_number
    FROM public.deliveries d
    WHERE d.assignment_status = 'OFFERED'
      AND d.assignment_expires_at IS NOT NULL
      AND d.assignment_expires_at < now()
      AND d.status IN ('RIDER_ASSIGNED', 'READY_FOR_PICKUP', 'AWAITING_RIDER')
    FOR UPDATE
  LOOP
    UPDATE public.deliveries
       SET rider_id = NULL,
           assignment_status = 'EXPIRED',
           assignment_offered_at = NULL,
           assignment_expires_at = NULL,
           status = 'AWAITING_RIDER',
           updated_at = now()
     WHERE id = v_row.id;

    UPDATE public.delivery_jobs
       SET partner_id = NULL, updated_at = now()
     WHERE order_id = v_row.order_id AND status NOT IN ('COMPLETED', 'CANCELLED');

    INSERT INTO public.delivery_events (delivery_id, status, note, actor_role)
    VALUES (v_row.id, 'AWAITING_RIDER', 'Rider assignment offer expired', 'SYSTEM');

    PERFORM public.delivery_audit(v_row.id, 'ASSIGNMENT_EXPIRED', 'RIDER_ASSIGNED', 'AWAITING_RIDER',
                                  'Offer expired without rider acceptance');

    SELECT user_id INTO v_user FROM public.delivery_partners WHERE id = v_row.rider_id;
    IF v_user IS NOT NULL THEN
      INSERT INTO public.notifications (user_id, title, message, type)
      VALUES (v_user, 'Delivery offer expired', 'The assignment for ' || v_row.delivery_number || ' expired before acceptance.', 'DELIVERY');
    END IF;

    v_count := v_count + 1;
  END LOOP;

  PERFORM set_config('goodsale.rider_system', 'off', true);
  RETURN v_count;
END;
$$;

CREATE OR REPLACE FUNCTION public.rider_available_deliveries()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  caller bigint := public.current_profile_id();
  p public.delivery_partners%ROWTYPE;
  v_pct numeric;
  v_result jsonb;
BEGIN
  IF caller IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;
  SELECT * INTO p FROM public.delivery_partners WHERE user_id = caller;
  IF NOT FOUND OR p.status <> 'APPROVED' THEN
    RAISE EXCEPTION 'Only approved riders can view delivery requests';
  END IF;
  IF NOT p.is_available THEN
    RETURN '[]'::jsonb;
  END IF;

  PERFORM public.expire_rider_assignments();

  v_pct := coalesce(p.commission_percentage,
                    (SELECT delivery_commission_percentage FROM public.revenue_settings ORDER BY id LIMIT 1),
                    10);

  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'id', d.id,
           'pickupCity', d.pickup_city,
           'pickupState', d.pickup_state,
           'deliveryCity', d.delivery_city,
           'deliveryState', d.delivery_state,
           'serviceType', d.service_type,
           'deliveryFee', d.delivery_fee,
           'riderNet', greatest(0, d.delivery_fee - round(d.delivery_fee * v_pct / 100.0)),
           'estimatedDeliveryDate', d.estimated_delivery_date,
           'status', d.status,
           'createdAt', d.created_at
         ) ORDER BY d.created_at), '[]'::jsonb)
    INTO v_result
  FROM public.deliveries d
  JOIN public.orders o ON o.id = d.order_id
  WHERE d.rider_id IS NULL
    AND d.delivery_method = 'GOODSALE_PARTNER'
    AND d.status IN ('READY_FOR_PICKUP', 'AWAITING_RIDER')
    AND d.assignment_status IN ('UNASSIGNED', 'REJECTED', 'EXPIRED')
    AND o.status NOT IN ('DISPUTED', 'CANCELLED', 'REFUNDED')
    AND NOT EXISTS (
      SELECT 1 FROM public.delivery_jobs j
      WHERE j.order_id = d.order_id
        AND j.partner_id IS NOT NULL
        AND j.status NOT IN ('COMPLETED', 'CANCELLED')
    )
    AND (
      (coalesce(array_length(p.service_states, 1), 0) > 0 AND d.delivery_state = ANY(p.service_states))
      OR (coalesce(array_length(p.service_states, 1), 0) = 0 AND (coalesce(p.state, '') = '' OR d.delivery_state = p.state))
      OR coalesce(p.state, '') = ''
    );

  RETURN coalesce(v_result, '[]'::jsonb);
END;
$$;

CREATE OR REPLACE FUNCTION public.rider_accept_delivery(p_delivery_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  d public.deliveries%ROWTYPE;
  p public.delivery_partners%ROWTYPE;
  caller bigint := public.current_profile_id();
  v_in_area boolean := true;
  v_seller bigint;
  v_buyer bigint;
BEGIN
  IF caller IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  SELECT * INTO p FROM public.delivery_partners WHERE user_id = caller FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Rider profile not found';
  END IF;
  IF p.status <> 'APPROVED' THEN
    RAISE EXCEPTION 'Only approved riders can accept deliveries';
  END IF;
  IF NOT p.is_available THEN
    RAISE EXCEPTION 'Go online before accepting deliveries';
  END IF;

  SELECT * INTO d FROM public.deliveries WHERE id = p_delivery_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Delivery not found';
  END IF;
  IF d.status IN ('DELIVERED', 'CANCELLED', 'RETURNED_TO_SELLER') THEN
    RAISE EXCEPTION 'This delivery is already closed';
  END IF;
  IF d.rider_id IS NOT NULL AND d.rider_id <> p.id THEN
    RAISE EXCEPTION 'This delivery is assigned to another rider';
  END IF;
  IF d.delivery_method <> 'GOODSALE_PARTNER' THEN
    RAISE EXCEPTION 'This delivery is not available to GoodDispatch riders';
  END IF;
  IF d.status NOT IN ('READY_FOR_PICKUP', 'AWAITING_RIDER', 'RIDER_ASSIGNED') THEN
    RAISE EXCEPTION 'This delivery is no longer available';
  END IF;

  IF d.assignment_status = 'OFFERED' AND d.assignment_expires_at IS NOT NULL AND d.assignment_expires_at < now() THEN
    PERFORM public.expire_rider_assignments();
    RAISE EXCEPTION 'This assignment offer has expired';
  END IF;

  -- Open requests must be inside the rider's operating area.
  IF d.assignment_status <> 'OFFERED' THEN
    IF coalesce(array_length(p.service_states, 1), 0) > 0 THEN
      v_in_area := d.delivery_state = ANY(p.service_states);
    ELSIF coalesce(p.state, '') <> '' THEN
      v_in_area := d.delivery_state = p.state;
    END IF;
    IF NOT v_in_area THEN
      RAISE EXCEPTION 'This delivery is outside your service area';
    END IF;
  END IF;

  SELECT o.seller_id, o.buyer_id INTO v_seller, v_buyer FROM public.orders o WHERE o.id = d.order_id;

  PERFORM set_config('goodsale.rider_system', 'on', true);

  UPDATE public.deliveries
     SET rider_id = p.id,
         rider_accepted_at = now(),
         assignment_status = 'ACCEPTED',
         assignment_expires_at = NULL,
         status = 'RIDER_ASSIGNED',
         updated_at = now()
   WHERE id = d.id;

  UPDATE public.delivery_jobs
     SET partner_id = p.id,
         status = CASE WHEN status = 'PENDING' THEN 'ACCEPTED' ELSE status END,
         updated_at = now()
   WHERE order_id = d.order_id AND status NOT IN ('COMPLETED', 'CANCELLED');

  INSERT INTO public.delivery_events (delivery_id, status, note, actor_id, actor_role)
  VALUES (d.id, 'RIDER_ASSIGNED', 'Rider ' || p.full_name || ' accepted the delivery', caller, 'RIDER');

  PERFORM public.delivery_audit(d.id, 'RIDER_ACCEPTED', d.status, 'RIDER_ASSIGNED',
                                'Rider #' || p.id || ' accepted the assignment');

  IF v_seller IS NOT NULL THEN
    INSERT INTO public.notifications (user_id, title, message, type)
    VALUES (v_seller, 'Rider assigned', p.full_name || ' accepted delivery ' || d.delivery_number || ' and will collect the package.', 'DELIVERY');
  END IF;

  INSERT INTO public.notifications (user_id, title, message, type)
  VALUES (p.user_id, 'Pickup reminder',
          'Collect ' || d.delivery_number || ' from ' || coalesce(nullif(d.pickup_address, ''), 'the seller') ||
          coalesce(', ' || nullif(d.pickup_city, ''), '') || '. Contact the seller from your active delivery if you need help.', 'DELIVERY');

  INSERT INTO public.notifications (user_id, title, message, type)
  VALUES (p.user_id, 'Delivery deadline',
          'Deliver ' || d.delivery_number || ' to ' || coalesce(nullif(d.delivery_city, ''), 'the buyer') ||
          CASE WHEN d.estimated_delivery_date IS NOT NULL
            THEN ' by ' || to_char(d.estimated_delivery_date, 'DD Mon YYYY')
            ELSE ' as soon as safely possible' END || '.', 'DELIVERY');

  PERFORM set_config('goodsale.rider_system', 'off', true);
  RETURN jsonb_build_object('success', true, 'status', 'RIDER_ASSIGNED', 'rider_id', p.id);
END;
$$;

