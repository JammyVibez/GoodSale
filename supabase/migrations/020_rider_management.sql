CREATE OR REPLACE FUNCTION public.create_rider_earning_for_delivery()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_pct numeric;
  v_commission numeric;
  v_net numeric;
BEGIN
  IF NEW.status = 'DELIVERED' AND OLD.status IS DISTINCT FROM 'DELIVERED' AND NEW.rider_id IS NOT NULL THEN
    PERFORM set_config('goodsale.rider_system', 'on', true);
    SELECT coalesce(dp.commission_percentage,
                    (SELECT delivery_commission_percentage FROM public.revenue_settings ORDER BY id LIMIT 1),
                    10)
      INTO v_pct
    FROM public.delivery_partners dp WHERE dp.id = NEW.rider_id;

    v_commission := round(coalesce(NEW.delivery_fee, 0) * coalesce(v_pct, 10) / 100.0);
    v_net := greatest(0, coalesce(NEW.delivery_fee, 0) - v_commission);

    INSERT INTO public.rider_earnings (
      delivery_id, order_id, rider_id, gross_amount, platform_commission, net_amount, status
    ) VALUES (
      NEW.id, NEW.order_id, NEW.rider_id, coalesce(NEW.delivery_fee, 0), v_commission, v_net, 'PENDING'
    )
    ON CONFLICT (delivery_id) DO NOTHING;

    UPDATE public.delivery_partners
       SET completed_deliveries = completed_deliveries + 1
     WHERE id = NEW.rider_id;

    INSERT INTO public.notifications (user_id, title, message, type)
    SELECT dp.user_id, 'Delivery completed',
           'Delivery ' || NEW.delivery_number || ' is complete. Your earning is pending approval.', 'EARNINGS'
    FROM public.delivery_partners dp WHERE dp.id = NEW.rider_id;

    PERFORM set_config('goodsale.rider_system', 'off', true);
  END IF;
  RETURN NEW;
END;
$$;

