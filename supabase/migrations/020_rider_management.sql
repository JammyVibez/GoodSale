-- Keep the rider's active counter accurate across acceptance, reassignment,
-- cancellation and completion without trusting client-side updates.
CREATE OR REPLACE FUNCTION public.sync_rider_active_delivery_count()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_terminal text[] := array['DELIVERED', 'FAILED_DELIVERY', 'RETURNED_TO_SELLER', 'CANCELLED'];
  v_old_active boolean := false;
  v_new_active boolean := false;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    v_old_active := OLD.rider_id IS NOT NULL
      AND OLD.assignment_status = 'ACCEPTED'
      AND NOT (OLD.status = ANY(v_terminal));
  END IF;
  v_new_active := NEW.rider_id IS NOT NULL
    AND NEW.assignment_status = 'ACCEPTED'
    AND NOT (NEW.status = ANY(v_terminal));

  IF v_old_active AND (NOT v_new_active OR OLD.rider_id IS DISTINCT FROM NEW.rider_id) THEN
    PERFORM set_config('goodsale.rider_system', 'on', true);
    UPDATE public.delivery_partners
       SET active_deliveries_count = greatest(0, active_deliveries_count - 1)
     WHERE id = OLD.rider_id;
    PERFORM set_config('goodsale.rider_system', 'off', true);
  END IF;

  IF v_new_active AND (NOT v_old_active OR OLD.rider_id IS DISTINCT FROM NEW.rider_id) THEN
    PERFORM set_config('goodsale.rider_system', 'on', true);
    UPDATE public.delivery_partners
       SET active_deliveries_count = active_deliveries_count + 1
     WHERE id = NEW.rider_id;
    PERFORM set_config('goodsale.rider_system', 'off', true);
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS deliveries_sync_rider_active ON public.deliveries;
CREATE TRIGGER deliveries_sync_rider_active
  AFTER INSERT OR UPDATE OF rider_id, assignment_status, status ON public.deliveries
  FOR EACH ROW EXECUTE FUNCTION public.sync_rider_active_delivery_count();

