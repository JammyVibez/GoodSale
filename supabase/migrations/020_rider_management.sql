CREATE OR REPLACE FUNCTION public.admin_set_rider_earning_status(
  p_earning_id bigint,
  p_status text,
  p_payout_reference text DEFAULT '',
  p_notes text DEFAULT ''
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  e public.rider_earnings%ROWTYPE;
  v_status text := upper(coalesce(p_status, ''));
  v_ref text := btrim(coalesce(p_payout_reference, ''));
  v_admin bigint := public.current_profile_id();
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Admins only';
  END IF;
  IF v_status NOT IN ('PENDING', 'APPROVED', 'PAID', 'VOID') THEN
    RAISE EXCEPTION 'Invalid earning status';
  END IF;
  IF v_status = 'PAID' AND v_ref = '' THEN
    RAISE EXCEPTION 'A payout reference is required before marking earnings paid';
  END IF;

  SELECT * INTO e FROM public.rider_earnings WHERE id = p_earning_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Earning not found';
  END IF;
  IF e.status = 'PAID' AND v_status <> 'PAID' THEN
    RAISE EXCEPTION 'Paid earnings cannot be reopened';
  END IF;

  UPDATE public.rider_earnings
     SET status = v_status,
         payout_reference = CASE WHEN v_status = 'PAID' THEN v_ref ELSE payout_reference END,
         notes = coalesce(nullif(btrim(p_notes), ''), notes),
         approved_at = CASE WHEN v_status = 'APPROVED' THEN coalesce(approved_at, now()) ELSE approved_at END,
         paid_at = CASE WHEN v_status = 'PAID' THEN coalesce(paid_at, now()) ELSE paid_at END,
         updated_at = now()
   WHERE id = e.id;

  INSERT INTO public.rider_earning_audit_logs (
    earning_id, rider_id, actor_id, actor_name, action, amount_before, amount_after, details
  )
  SELECT e.id, e.rider_id, v_admin, coalesce(p.full_name, 'Admin'),
         'STATUS_' || v_status, e.net_amount, e.net_amount,
         'Earning status changed from ' || e.status || ' to ' || v_status ||
         coalesce(' · payout ref ' || nullif(v_ref, ''), '')
  FROM public.profiles p WHERE p.id = v_admin;

  INSERT INTO public.notifications (user_id, title, message, type)
  SELECT dp.user_id,
         CASE v_status WHEN 'PAID' THEN 'Earnings paid' WHEN 'APPROVED' THEN 'Earnings approved' ELSE 'Earnings update' END,
         'Delivery earning #' || e.id || ' is now ' || v_status ||
         CASE WHEN v_status = 'PAID' THEN ' · ref ' || v_ref ELSE '' END,
         'EARNINGS'
  FROM public.delivery_partners dp WHERE dp.id = e.rider_id;

  RETURN jsonb_build_object('success', true, 'status', v_status);
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_adjust_rider_earning(
  p_earning_id bigint,
  p_delta numeric,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  e public.rider_earnings%ROWTYPE;
  v_admin bigint := public.current_profile_id();
  v_reason text := btrim(coalesce(p_reason, ''));
  v_new_adjustment numeric;
  v_new_net numeric;
  v_name text;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Admins only';
  END IF;
  IF p_delta IS NULL OR p_delta = 0 THEN
    RAISE EXCEPTION 'Enter a non-zero adjustment';
  END IF;
  IF v_reason = '' THEN
    RAISE EXCEPTION 'An adjustment reason is required';
  END IF;

  SELECT * INTO e FROM public.rider_earnings WHERE id = p_earning_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Earning not found';
  END IF;
  IF e.status IN ('PAID', 'VOID') THEN
    RAISE EXCEPTION 'Paid or voided earnings cannot be adjusted';
  END IF;

  v_new_adjustment := coalesce(e.adjustment_amount, 0) + p_delta;
  v_new_net := greatest(0, e.gross_amount - e.platform_commission + v_new_adjustment);

  UPDATE public.rider_earnings
     SET adjustment_amount = v_new_adjustment,
         net_amount = v_new_net,
         notes = v_reason,
         updated_at = now()
   WHERE id = e.id;

  SELECT full_name INTO v_name FROM public.profiles WHERE id = v_admin;

  INSERT INTO public.rider_earning_audit_logs (
    earning_id, rider_id, actor_id, actor_name, action, amount_before, amount_after, details
  ) VALUES (
    e.id, e.rider_id, v_admin, coalesce(v_name, 'Admin'), 'ADJUSTMENT',
    e.net_amount, v_new_net, v_reason
  );

  INSERT INTO public.notifications (user_id, title, message, type)
  SELECT dp.user_id, 'Earnings adjusted',
         'Your delivery earning was adjusted by ₦' || round(p_delta)::text || '. Reason: ' || v_reason,
         'EARNINGS'
  FROM public.delivery_partners dp WHERE dp.id = e.rider_id;

  RETURN jsonb_build_object('success', true, 'net_amount', v_new_net, 'adjustment_amount', v_new_adjustment);
END;
$$;

