-- =============================================================================
-- 023 — Premium subscriptions: server-verified Paystack checkout
--
-- The old browser path wrote subscription rows directly to these tables under
-- permissive RLS, so a client could grant itself benefits. This migration:
--   1. removes client INSERT/UPDATE access to subscription tables,
--   2. records subscription checkout intents,
--   3. activates a subscription only through a service-role RPC after Paystack
--      verification (or a signed webhook),
--   4. adds an admin-configurable subscription duration.
--
-- Existing active subscription rows are left untouched.
-- =============================================================================

ALTER TABLE public.revenue_settings
  ADD COLUMN IF NOT EXISTS premium_duration_days integer NOT NULL DEFAULT 30;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'revenue_settings_premium_duration_check'
  ) THEN
    ALTER TABLE public.revenue_settings
      ADD CONSTRAINT revenue_settings_premium_duration_check
      CHECK (premium_duration_days BETWEEN 1 AND 366);
  END IF;
END $$;

-- Subscription rows gain an explicit lifecycle without changing existing data.
ALTER TABLE public.business_subscriptions
  ADD COLUMN IF NOT EXISTS starts_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'ACTIVE',
  ADD COLUMN IF NOT EXISTS auto_renew boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS cancelled_at timestamptz,
  ADD COLUMN IF NOT EXISTS last_payment_reference text;

ALTER TABLE public.verified_plus_subscriptions
  ADD COLUMN IF NOT EXISTS starts_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'ACTIVE',
  ADD COLUMN IF NOT EXISTS auto_renew boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS cancelled_at timestamptz,
  ADD COLUMN IF NOT EXISTS last_payment_reference text;

CREATE TABLE IF NOT EXISTS public.premium_subscription_payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  product text NOT NULL CHECK (product IN ('VERIFIED_PLUS', 'BUSINESS')),
  plan_code text NOT NULL DEFAULT 'VERIFIED_PLUS',
  reference text UNIQUE NOT NULL,
  amount numeric NOT NULL CHECK (amount > 0),
  currency text NOT NULL DEFAULT 'NGN',
  status text NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'ABANDONED')),
  provider text NOT NULL DEFAULT 'paystack',
  provider_reference text,
  starts_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  paid_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_premium_payments_user_id
  ON public.premium_subscription_payments(user_id);
CREATE INDEX IF NOT EXISTS idx_premium_payments_status
  ON public.premium_subscription_payments(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_premium_payments_reference
  ON public.premium_subscription_payments(reference);

ALTER TABLE public.premium_subscription_payments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS premium_payments_own_read ON public.premium_subscription_payments;
CREATE POLICY premium_payments_own_read ON public.premium_subscription_payments
  FOR SELECT TO authenticated
  USING (user_id = public.current_profile_id() OR public.is_admin());

-- The browser may read its own subscriptions, but only the service role may
-- create or mutate them. The RPC below runs with definer rights.
DROP POLICY IF EXISTS business_subscriptions_own_insert ON public.business_subscriptions;
DROP POLICY IF EXISTS business_subscriptions_admin_update ON public.business_subscriptions;
DROP POLICY IF EXISTS business_subscriptions_admin_all ON public.business_subscriptions;
CREATE POLICY business_subscriptions_admin_all ON public.business_subscriptions
  FOR ALL TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS verified_plus_own_insert ON public.verified_plus_subscriptions;
DROP POLICY IF EXISTS verified_plus_admin_update ON public.verified_plus_subscriptions;
DROP POLICY IF EXISTS verified_plus_admin_all ON public.verified_plus_subscriptions;
CREATE POLICY verified_plus_admin_all ON public.verified_plus_subscriptions
  FOR ALL TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

-- The paid member label is publicly visible (and explicitly separate from
-- identity verification). Expired rows stay private through the own-read policy.
DROP POLICY IF EXISTS verified_plus_active_public_read ON public.verified_plus_subscriptions;
CREATE POLICY verified_plus_active_public_read ON public.verified_plus_subscriptions
  FOR SELECT TO authenticated
  USING (expires_at > now());

/*
 * Activate one paid subscription intent.
 *
 * Called only by the service-role verification route or the signed Paystack
 * webhook. The payment row is locked, its status is re-checked, and activation
 * is idempotent on the provider reference.
 */
CREATE OR REPLACE FUNCTION public.activate_premium_subscription(
  p_reference text,
  p_provider_reference text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_payment public.premium_subscription_payments%ROWTYPE;
  v_duration integer;
  v_base timestamptz;
  v_expiry timestamptz;
  v_current_expiry timestamptz;
  v_subscription_id bigint;
  v_plan text;
BEGIN
  IF p_reference IS NULL OR length(trim(p_reference)) = 0 THEN
    RAISE EXCEPTION 'A payment reference is required';
  END IF;

  SELECT * INTO v_payment
  FROM public.premium_subscription_payments
  WHERE reference = p_reference
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Premium payment was not created by GoodSale';
  END IF;

  IF v_payment.status = 'SUCCESS' THEN
    RETURN jsonb_build_object(
      'success', true,
      'alreadyActive', true,
      'reference', v_payment.reference,
      'product', v_payment.product,
      'planCode', v_payment.plan_code,
      'expiresAt', v_payment.expires_at
    );
  END IF;

  IF v_payment.status <> 'PENDING' THEN
    RAISE EXCEPTION 'This subscription payment is no longer payable';
  END IF;

  SELECT GREATEST(coalesce(premium_duration_days, 30), 1)
    INTO v_duration
  FROM public.revenue_settings
  ORDER BY id
  LIMIT 1;

  v_duration := coalesce(v_duration, 30);
  v_base := now();

  IF v_payment.product = 'VERIFIED_PLUS' THEN
    SELECT id, expires_at
      INTO v_subscription_id, v_current_expiry
    FROM public.verified_plus_subscriptions
    WHERE user_id = v_payment.user_id
    ORDER BY expires_at DESC
    LIMIT 1;

    IF v_current_expiry IS NOT NULL AND v_current_expiry > now() THEN
      v_base := v_current_expiry;
    END IF;
    v_expiry := v_base + make_interval(days => v_duration);

    IF v_subscription_id IS NULL THEN
      INSERT INTO public.verified_plus_subscriptions
        (user_id, starts_at, expires_at, status, auto_renew, last_payment_reference)
      VALUES
        (v_payment.user_id, v_base, v_expiry, 'ACTIVE', false, p_reference)
      RETURNING id INTO v_subscription_id;
    ELSE
      UPDATE public.verified_plus_subscriptions
      SET starts_at = v_base,
          expires_at = v_expiry,
          status = 'ACTIVE',
          auto_renew = false,
          cancelled_at = NULL,
          last_payment_reference = p_reference
      WHERE id = v_subscription_id;
    END IF;

    v_plan := 'VERIFIED_PLUS';
  ELSE
    SELECT id, expires_at
      INTO v_subscription_id, v_current_expiry
    FROM public.business_subscriptions
    WHERE user_id = v_payment.user_id
    ORDER BY expires_at DESC
    LIMIT 1;

    IF v_current_expiry IS NOT NULL AND v_current_expiry > now() THEN
      v_base := v_current_expiry;
    END IF;
    v_expiry := v_base + make_interval(days => v_duration);

    IF v_subscription_id IS NULL THEN
      INSERT INTO public.business_subscriptions
        (user_id, plan, starts_at, expires_at, status, auto_renew, last_payment_reference)
      VALUES
        (v_payment.user_id, v_payment.plan_code, v_base, v_expiry, 'ACTIVE', false, p_reference)
      RETURNING id INTO v_subscription_id;
    ELSE
      UPDATE public.business_subscriptions
      SET plan = v_payment.plan_code,
          starts_at = v_base,
          expires_at = v_expiry,
          status = 'ACTIVE',
          auto_renew = false,
          cancelled_at = NULL,
          last_payment_reference = p_reference
      WHERE id = v_subscription_id;
    END IF;

    v_plan := v_payment.plan_code;
  END IF;

  UPDATE public.premium_subscription_payments
  SET status = 'SUCCESS',
      provider_reference = coalesce(p_provider_reference, provider_reference, p_reference),
      starts_at = v_base,
      expires_at = v_expiry,
      paid_at = now()
  WHERE id = v_payment.id;

  INSERT INTO public.audit_logs
    (user_id, action, entity_type, entity_id, details)
  VALUES
    (v_payment.user_id, 'PREMIUM_SUBSCRIPTION_ACTIVATED', 'PREMIUM_SUBSCRIPTION',
     v_subscription_id,
     format('%s activated for %s day(s) through payment %s',
            v_plan, v_duration, p_reference));

  INSERT INTO public.notifications
    (user_id, title, message, type, is_read, created_at)
  VALUES
    (v_payment.user_id,
     'Premium membership active',
     format('Your %s membership is active until %s.',
            CASE WHEN v_payment.product = 'VERIFIED_PLUS' THEN 'Verified+' ELSE 'Business' END,
            to_char(v_expiry AT TIME ZONE 'Africa/Lagos', 'DD Mon YYYY')),
     'WALLET',
     false,
     now());

  RETURN jsonb_build_object(
    'success', true,
    'alreadyActive', false,
    'reference', p_reference,
    'product', v_payment.product,
    'planCode', v_plan,
    'startsAt', v_base,
    'expiresAt', v_expiry
  );
END;
$$;

REVOKE ALL ON FUNCTION public.activate_premium_subscription(text, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.activate_premium_subscription(text, text) FROM anon;
REVOKE ALL ON FUNCTION public.activate_premium_subscription(text, text) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.activate_premium_subscription(text, text) TO service_role;

GRANT SELECT ON public.premium_subscription_payments TO authenticated;

NOTIFY pgrst, 'reload schema';
