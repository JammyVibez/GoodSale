-- 022_premium_tracking.sql
-- Phase 4: premium checkout and shipment tracking.
--
-- Additive only. Orders, escrow, payment verification and Phase 1-3 delivery
-- records remain the source of truth. This migration adds:
--   * buyer saved addresses for checkout
--   * a checkout group so multi-seller carts present as one order journey
--   * a separate, unique GoodSale shipment tracking id on every delivery
--   * date-based order numbers (GS-YYYYMMDD-NNNNN)
--   * a redacted public tracking lookup that never exposes participant PII
--     unless the caller is the buyer, seller, assigned rider or an admin.

-- ---------------------------------------------------------------------------
-- 1. Saved checkout addresses
-- ---------------------------------------------------------------------------
create table if not exists public.buyer_addresses (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  label text not null default 'Home',
  contact_name text not null default '',
  phone text not null default '',
  state text not null default '',
  city text not null default '',
  area text not null default '',
  street text not null default '',
  landmark text not null default '',
  instructions text not null default '',
  lat double precision,
  lng double precision,
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_buyer_addresses_profile
  on public.buyer_addresses(profile_id, is_default desc, updated_at desc);

alter table public.buyer_addresses enable row level security;

drop policy if exists buyer_addresses_own_select on public.buyer_addresses;
create policy buyer_addresses_own_select on public.buyer_addresses
  for select to authenticated
  using (profile_id = public.current_profile_id());

drop policy if exists buyer_addresses_own_insert on public.buyer_addresses;
create policy buyer_addresses_own_insert on public.buyer_addresses
  for insert to authenticated
  with check (profile_id = public.current_profile_id());

drop policy if exists buyer_addresses_own_update on public.buyer_addresses;
create policy buyer_addresses_own_update on public.buyer_addresses
  for update to authenticated
  using (profile_id = public.current_profile_id())
  with check (profile_id = public.current_profile_id());

drop policy if exists buyer_addresses_own_delete on public.buyer_addresses;
create policy buyer_addresses_own_delete on public.buyer_addresses
  for delete to authenticated
  using (profile_id = public.current_profile_id());

grant select, insert, update, delete on public.buyer_addresses to authenticated;
grant usage, select on sequence public.buyer_addresses_id_seq to authenticated;

drop trigger if exists buyer_addresses_set_updated_at on public.buyer_addresses;
create trigger buyer_addresses_set_updated_at
  before update on public.buyer_addresses
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- 2. Checkout grouping and delivery contact/instructions
-- ---------------------------------------------------------------------------
alter table public.orders
  add column if not exists checkout_group_id text not null default '',
  add column if not exists delivery_phone text not null default '',
  add column if not exists delivery_instructions text not null default '';

create index if not exists idx_orders_checkout_group
  on public.orders(checkout_group_id)
  where checkout_group_id <> '';

alter table public.deliveries
  add column if not exists delivery_phone text not null default '',
  add column if not exists tracking_id text;

-- ---------------------------------------------------------------------------
-- 3. Date-based order numbers
-- Existing GS-YYYY-NNNNNN rows are kept. New inserts (including older clients
-- that still send the legacy format) receive GS-YYYYMMDD-NNNNN.
-- ---------------------------------------------------------------------------
create or replace function public.assign_order_number()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  candidate text;
begin
  if new.order_number is not null
     and btrim(new.order_number) <> ''
     and new.order_number !~ '^GS-[0-9]{4}-[0-9]{6}$' then
    return new;
  end if;

  loop
    candidate := 'GS-' || to_char(now(), 'YYYYMMDD') || '-' ||
      lpad((10000 + floor(random() * 90000))::int::text, 5, '0');
    exit when not exists (
      select 1 from public.orders where order_number = candidate
    );
  end loop;

  new.order_number := candidate;
  return new;
end;
$$;

drop trigger if exists orders_assign_order_number on public.orders;
create trigger orders_assign_order_number
  before insert on public.orders
  for each row execute function public.assign_order_number();

-- ---------------------------------------------------------------------------
-- 4. Unique GoodSale shipment tracking ids
-- ---------------------------------------------------------------------------
create or replace function public.generate_shipment_tracking_id()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  candidate text;
begin
  loop
    candidate := 'GSD-' || lpad((100000000 + floor(random() * 900000000))::bigint::text, 9, '0');
    exit when not exists (
      select 1 from public.deliveries where tracking_id = candidate
    );
  end loop;
  return candidate;
end;
$$;

do $$
declare
  r record;
begin
  for r in select id from public.deliveries where tracking_id is null or btrim(tracking_id) = '' loop
    update public.deliveries
       set tracking_id = public.generate_shipment_tracking_id()
     where id = r.id;
  end loop;
end;
$$;

alter table public.deliveries
  alter column tracking_id set default public.generate_shipment_tracking_id();

update public.deliveries
   set tracking_id = public.generate_shipment_tracking_id()
 where tracking_id is null or btrim(tracking_id) = '';

create unique index if not exists idx_deliveries_tracking_id_unique
  on public.deliveries(tracking_id);

alter table public.deliveries
  alter column tracking_id set not null;

create index if not exists idx_deliveries_tracking_number
  on public.deliveries(tracking_number)
  where tracking_number <> '';

-- Re-create the order -> delivery trigger so contact and instructions are
-- carried into the delivery record, and the tracking id is issued at creation.
create or replace function public.create_delivery_for_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pickup record;
  v_delivery_id bigint;
  v_status text;
  v_eta date;
begin
  if coalesce(new.delivery_method, '') = 'PICKUP' then
    return new;
  end if;

  select pickup_address, pickup_city, pickup_state, pickup_lat, pickup_lng
    into v_pickup
  from public.seller_shipping_settings
  where seller_id = new.seller_id;

  v_status := public.delivery_status_from_order(new.status);

  v_eta := case
    when new.estimated_delivery_max_days is not null
      then (new.created_at::date + new.estimated_delivery_max_days)
    else null
  end;

  insert into public.deliveries (
    order_id, delivery_number, tracking_id, buyer_id, seller_id,
    pickup_address, pickup_city, pickup_state,
    delivery_address, delivery_city, delivery_state, delivery_phone,
    delivery_instructions,
    pickup_lat, pickup_lng, delivery_lat, delivery_lng,
    delivery_method, service_type, delivery_fee, fee_snapshot,
    status, rider_id, estimated_delivery_date, created_at
  ) values (
    new.id,
    'DLV-' || new.order_number,
    public.generate_shipment_tracking_id(),
    new.buyer_id,
    new.seller_id,
    coalesce(v_pickup.pickup_address, ''),
    coalesce(v_pickup.pickup_city, ''),
    coalesce(v_pickup.pickup_state, ''),
    coalesce(new.delivery_address, ''),
    coalesce(new.delivery_city, ''),
    coalesce(new.delivery_state, ''),
    coalesce(new.delivery_phone, ''),
    coalesce(new.delivery_instructions, ''),
    coalesce(v_pickup.pickup_lat, new.pickup_lat),
    coalesce(v_pickup.pickup_lng, new.pickup_lng),
    new.delivery_lat,
    new.delivery_lng,
    coalesce(nullif(new.delivery_method, ''), 'GOODSALE_PARTNER'),
    coalesce(new.service_type, 'STANDARD'),
    coalesce(new.delivery_fee, 0),
    coalesce(new.shipping_snapshot, '{}'::jsonb),
    v_status,
    new.selected_partner_id,
    v_eta,
    new.created_at
  )
  on conflict (order_id) do nothing
  returning id into v_delivery_id;

  if v_delivery_id is not null then
    insert into public.delivery_events (delivery_id, status, note, actor_role)
    values (v_delivery_id, v_status, 'Delivery record created with the order', 'SYSTEM');
  end if;

  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- 5. Public / participant tracking lookup
-- ---------------------------------------------------------------------------
create or replace function public.shipment_tracking_lookup(p_query text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_query text := upper(btrim(coalesce(p_query, '')));
  d public.deliveries%rowtype;
  o public.orders%rowtype;
  p public.delivery_partners%rowtype;
  caller bigint := public.current_profile_id();
  v_authorized boolean := false;
  v_is_admin boolean := public.is_admin();
  v_viewer_role text := '';
  v_events jsonb := '[]'::jsonb;
  v_shipments jsonb := '[]'::jsonb;
  v_rider jsonb := null;
  v_live jsonb := null;
  v_destination jsonb;
  v_order jsonb := null;
  v_last timestamptz;
  v_delivery_pin text := null;
  v_seller_name text := '';
begin
  if v_query = '' then
    return jsonb_build_object('found', false);
  end if;

  select * into d
  from public.deliveries dl
  where upper(dl.tracking_id) = v_query
     or upper(dl.delivery_number) = v_query
     or upper(dl.tracking_number) = v_query
  order by dl.created_at desc
  limit 1;

  if not found then
    select dd.* into d
    from public.deliveries dd
    join public.orders oo on oo.id = dd.order_id
    where upper(oo.order_number) = v_query
    order by dd.created_at desc
    limit 1;
  end if;

  if not found then
    return jsonb_build_object('found', false);
  end if;

  select * into o from public.orders where id = d.order_id;
  v_authorized := coalesce(v_is_admin, false)
    or coalesce(o.buyer_id = caller, false)
    or coalesce(o.seller_id = caller, false);

  if not v_authorized and d.rider_id is not null then
    select * into p from public.delivery_partners where id = d.rider_id;
    if found and p.user_id = caller then
      v_authorized := true;
    end if;
  end if;

  if v_authorized then
    v_viewer_role := case
      when coalesce(v_is_admin, false) then 'ADMIN'
      when o.buyer_id = caller then 'BUYER'
      when o.seller_id = caller then 'SELLER'
      when d.rider_id is not null and p.user_id = caller then 'RIDER'
      else 'PARTICIPANT'
    end;
  end if;

  -- Timeline: real events only. Notes can contain addresses or names, so they
  -- are disclosed only to authorized participants.
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', e.id,
           'status', e.status,
           'note', case when v_authorized then e.note else '' end,
           'actor_role', case when v_authorized then e.actor_role else '' end,
           'created_at', e.created_at
         ) order by e.created_at asc), '[]'::jsonb)
    into v_events
  from public.delivery_events e
  where e.delivery_id = d.id;

  select max(e.created_at) into v_last
  from public.delivery_events e
  where e.delivery_id = d.id;

  if d.rider_id is not null then
    select * into p from public.delivery_partners where id = d.rider_id;
  end if;

  if v_authorized then
    if d.rider_id is not null then
      v_rider := jsonb_build_object(
        'id', p.id,
        'name', p.full_name,
        'photo_url', p.photo_url,
        'phone', p.phone,
        'vehicle_type', p.vehicle_type,
        'vehicle', concat_ws(' ', nullif(p.brand, ''), nullif(p.model, '')),
        'plate_number', p.plate_number,
        'rating', p.rating,
        'completed_deliveries', p.completed_deliveries,
        'trust_score', p.trust_score
      );
    end if;

    v_live := public.delivery_tracking_view(d.id);

    select jsonb_build_object(
      'id', o.id,
      'order_number', o.order_number,
      'checkout_group_id', o.checkout_group_id,
      'product_title', o.product_title,
      'product_image', o.product_image,
      'total_amount', o.total_amount,
      'delivery_fee', o.delivery_fee,
      'payment_method', o.payment_method,
      'status', o.status,
      'created_at', o.created_at,
      'delivered_at', d.delivered_at,
      'confirmed_at', d.confirmed_at
    ) into v_order;

    v_delivery_pin := case when o.buyer_id = caller then o.delivery_pin else null end;

    v_destination := jsonb_build_object(
      'address', d.delivery_address,
      'city', d.delivery_city,
      'state', d.delivery_state,
      'phone', d.delivery_phone,
      'instructions', d.delivery_instructions,
      'lat', d.delivery_lat,
      'lng', d.delivery_lng
    );

    select full_name into v_seller_name
    from public.profiles where id = d.seller_id;

    -- Other seller shipments in the same checkout group, without PII.
    select coalesce(jsonb_agg(jsonb_build_object(
             'tracking_id', s.tracking_id,
             'status', s.status,
             'seller_name', sp.full_name,
             'product_title', so.product_title,
             'is_current', s.id = d.id
           ) order by s.created_at asc), '[]'::jsonb)
      into v_shipments
    from public.deliveries s
    join public.orders so on so.id = s.order_id
    left join public.profiles sp on sp.id = s.seller_id
    where so.checkout_group_id <> ''
      and so.checkout_group_id = o.checkout_group_id
      and (s.id = d.id or v_viewer_role in ('BUYER', 'ADMIN'));
  else
    v_destination := jsonb_build_object(
      'address', '',
      'city', d.delivery_city,
      'state', d.delivery_state,
      'phone', '',
      'instructions', '',
      'lat', null,
      'lng', null
    );
  end if;

  if v_last is null then v_last := d.updated_at; end if;

  return jsonb_build_object(
    'found', true,
    'delivery_id', d.id,
    'tracking_id', d.tracking_id,
    'delivery_number', d.delivery_number,
    'order_number', o.order_number,
    'checkout_group_id', o.checkout_group_id,
    'status', d.status,
    'delivery_method', d.delivery_method,
    'service_type', d.service_type,
    'courier_name', d.courier_name,
    'courier_tracking_number', d.tracking_number,
    'estimated_delivery_date', d.estimated_delivery_date,
    'created_at', d.created_at,
    'delivered_at', d.delivered_at,
    'confirmed_at', d.confirmed_at,
    'cancelled_at', d.cancelled_at,
    'last_updated', v_last,
    'authorized', coalesce(v_authorized, false),
    'access_level', case when coalesce(v_is_admin, false) then 'ADMIN' when v_authorized then 'PARTICIPANT' else 'PUBLIC' end,
    'viewer_role', v_viewer_role,
    'destination', v_destination,
    'events', v_events,
    'rider', v_rider,
    'live', v_live,
    'order', v_order,
    'shipments', v_shipments,
    'seller_name', case when v_authorized then v_seller_name else '' end,
    'delivery_pin', v_delivery_pin,
    'can_confirm_receipt', coalesce(v_authorized, false) and coalesce(o.buyer_id = caller, false) and d.status = 'DELIVERED',
    'can_report_issue', coalesce(v_authorized, false) and coalesce(o.buyer_id = caller, false)
      and d.status not in ('CANCELLED', 'RETURNED_TO_SELLER')
  );
end;
$$;

revoke all on function public.shipment_tracking_lookup(text) from public;
grant execute on function public.shipment_tracking_lookup(text) to anon, authenticated;

-- Keep the delivery tracking API's shape in sync for the new shipment id.
create or replace function public.delivery_tracking_public_id(p_delivery_id bigint)
returns text
language sql
security definer
set search_path = public
as $$
  select tracking_id from public.deliveries where id = p_delivery_id;
$$;

grant execute on function public.delivery_tracking_public_id(bigint) to anon, authenticated;

comment on column public.deliveries.tracking_id is
  'Unique GoodSale shipment tracking id (GSD-#########), separate from order and courier tracking numbers.';
comment on column public.orders.checkout_group_id is
  'Groups the seller sub-orders created by one checkout so multi-seller shipments remain one journey.';
