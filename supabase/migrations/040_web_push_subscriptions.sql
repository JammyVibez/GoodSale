-- 040 — Web Push subscriptions for escrow, dispute resolution, and chat alerts.
BEGIN;

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE,
  p256dh text NOT NULL,
  auth text NOT NULL,
  user_agent text NOT NULL DEFAULT '',
  platform text NOT NULL DEFAULT 'web'
    CHECK (platform IN ('web', 'ios', 'android', 'desktop')),
  topics jsonb NOT NULL DEFAULT '{"escrow":true,"disputes":true,"messages":true}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_push_subscriptions_profile_updated
  ON public.push_subscriptions(profile_id, updated_at DESC);

ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS push_subscriptions_owner_read ON public.push_subscriptions;
CREATE POLICY push_subscriptions_owner_read ON public.push_subscriptions
  FOR SELECT TO authenticated USING (profile_id = public.current_profile_id());

DROP POLICY IF EXISTS push_subscriptions_owner_insert ON public.push_subscriptions;
CREATE POLICY push_subscriptions_owner_insert ON public.push_subscriptions
  FOR INSERT TO authenticated WITH CHECK (profile_id = public.current_profile_id());

DROP POLICY IF EXISTS push_subscriptions_owner_update ON public.push_subscriptions;
CREATE POLICY push_subscriptions_owner_update ON public.push_subscriptions
  FOR UPDATE TO authenticated
  USING (profile_id = public.current_profile_id())
  WITH CHECK (profile_id = public.current_profile_id());

DROP POLICY IF EXISTS push_subscriptions_owner_delete ON public.push_subscriptions;
CREATE POLICY push_subscriptions_owner_delete ON public.push_subscriptions
  FOR DELETE TO authenticated USING (profile_id = public.current_profile_id());

COMMIT;
