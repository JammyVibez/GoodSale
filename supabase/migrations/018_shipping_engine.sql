insert into public.shipping_distance_tiers (label, min_km, max_km, fee, enabled, priority)
select * from (values
  ('0–3 km', 0::numeric, 3::numeric, 1000::numeric, true, 10),
  ('3–7 km', 3::numeric, 7::numeric, 1500::numeric, true, 20),
  ('7–15 km', 7::numeric, 15::numeric, 2500::numeric, true, 30)
) as defaults(label, min_km, max_km, fee, enabled, priority)
where not exists (select 1 from public.shipping_distance_tiers);

