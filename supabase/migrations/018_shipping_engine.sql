-- ---------------------------------------------------------------------------
-- Pricing rules (higher priority wins)
-- ---------------------------------------------------------------------------
create table if not exists public.shipping_rules (
  id bigint generated by default as identity primary key,
  name text not null,
  enabled boolean not null default true,
  priority integer not null default 0,
  scope text not null default 'GLOBAL' check (scope in ('GLOBAL','STATE','CITY','ZONE')),
  zone_id bigint references public.shipping_zones(id) on delete set null,
  state text not null default '',
  city text not null default '',
  origin_state text not null default '',
  origin_city text not null default '',
  delivery_method text not null default 'ANY'
    check (delivery_method in ('ANY','GOODSALE_PARTNER','THIRD_PARTY_COURIER','PICKUP')),
  service_type text not null default 'ANY'
    check (service_type in ('ANY','ECONOMY','STANDARD','EXPRESS')),
  base_fee numeric check (base_fee is null or base_fee >= 0),
  per_km_fee numeric check (per_km_fee is null or per_km_fee >= 0),
  min_fee numeric check (min_fee is null or min_fee >= 0),
  max_fee numeric check (max_fee is null or max_fee >= 0),
  weight_per_kg numeric check (weight_per_kg is null or weight_per_kg >= 0),
  oversize_surcharge numeric check (oversize_surcharge is null or oversize_surcharge >= 0),
  remote_surcharge numeric check (remote_surcharge is null or remote_surcharge >= 0),
  free_shipping_threshold numeric check (free_shipping_threshold is null or free_shipping_threshold >= 0),
  handling_fee numeric check (handling_fee is null or handling_fee >= 0),
  platform_fee numeric check (platform_fee is null or platform_fee >= 0),
  seller_sponsored boolean not null default false,
  platform_sponsored boolean not null default false,
  eta_min_days integer check (eta_min_days is null or eta_min_days >= 0),
  eta_max_days integer check (eta_max_days is null or eta_max_days >= 0),
  manual_quote boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (min_fee is null or max_fee is null or max_fee >= min_fee),
  check (eta_min_days is null or eta_max_days is null or eta_max_days >= eta_min_days)
);

