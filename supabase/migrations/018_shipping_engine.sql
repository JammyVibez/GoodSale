-- 018_shipping_engine.sql
-- Database-driven shipping rules, zones, courier adapters, seller settings,
-- manual quotations and immutable order shipping snapshots.
-- Additive only: existing checkout/order behavior remains compatible.

-- ---------------------------------------------------------------------------
-- Global shipping settings (single row, id = 1)
-- ---------------------------------------------------------------------------
create table if not exists public.shipping_settings (
  id smallint primary key default 1 check (id = 1),
  enabled boolean not null default true,
  local_base_fee numeric not null default 1000 check (local_base_fee >= 0),
  per_km_fee numeric not null default 0 check (per_km_fee >= 0),
  min_fee numeric not null default 500 check (min_fee >= 0),
  max_fee numeric not null default 50000 check (max_fee >= 0),
  interstate_base_fee numeric not null default 3500 check (interstate_base_fee >= 0),
  interstate_per_km_fee numeric not null default 100 check (interstate_per_km_fee >= 0),
  weight_surcharge_per_kg numeric not null default 0 check (weight_surcharge_per_kg >= 0),
  oversize_surcharge numeric not null default 0 check (oversize_surcharge >= 0),
  remote_surcharge numeric not null default 1500 check (remote_surcharge >= 0),
  free_shipping_threshold numeric not null default 0 check (free_shipping_threshold >= 0),
  handling_fee numeric not null default 0 check (handling_fee >= 0),
  platform_shipping_fee numeric not null default 0 check (platform_shipping_fee >= 0),
  economy_fee numeric not null default 0 check (economy_fee >= 0),
  standard_fee numeric not null default 0 check (standard_fee >= 0),
  express_fee numeric not null default 2500 check (express_fee >= 0),
  manual_quote_above_km numeric not null default 15 check (manual_quote_above_km >= 0),
  manual_quotes_enabled boolean not null default true,
  seller_sponsored_shipping boolean not null default true,
  platform_sponsored_shipping boolean not null default false,
  default_eta_min_days integer not null default 1 check (default_eta_min_days >= 0),
  default_eta_max_days integer not null default 7 check (default_eta_max_days >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (max_fee >= min_fee),
  check (default_eta_max_days >= default_eta_min_days)
);

drop trigger if exists shipping_settings_set_updated_at on public.shipping_settings;
create trigger shipping_settings_set_updated_at
  before update on public.shipping_settings
  for each row execute function public.set_updated_at();

alter table public.shipping_settings enable row level security;
drop policy if exists shipping_settings_public_read on public.shipping_settings;
create policy shipping_settings_public_read on public.shipping_settings for select using (true);
drop policy if exists shipping_settings_admin_insert on public.shipping_settings;
create policy shipping_settings_admin_insert on public.shipping_settings
  for insert to authenticated with check (public.is_admin());
drop policy if exists shipping_settings_admin_update on public.shipping_settings;
create policy shipping_settings_admin_update on public.shipping_settings
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

insert into public.shipping_settings (id) values (1) on conflict (id) do nothing;

