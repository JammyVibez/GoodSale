-- ---------------------------------------------------------------------------
-- Immutable shipping snapshot on each order
-- ---------------------------------------------------------------------------
alter table public.orders
  add column if not exists shipping_rule_id bigint references public.shipping_rules(id) on delete set null,
  add column if not exists shipping_zone_id bigint references public.shipping_zones(id) on delete set null,
  add column if not exists shipping_quote_id uuid references public.shipping_quotes(id) on delete set null,
  add column if not exists shipping_snapshot jsonb not null default '{}'::jsonb,
  add column if not exists estimated_delivery_min_days integer,
  add column if not exists estimated_delivery_max_days integer;

create index if not exists idx_orders_shipping_rule_id on public.orders(shipping_rule_id);

