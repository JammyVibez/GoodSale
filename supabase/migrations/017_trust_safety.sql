-- 017_trust_safety.sql
-- Trust, safety, support and moderation records.
-- Additive only: no existing table or column is modified destructively.

create table if not exists public.support_tickets (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  user_id bigint not null references public.profiles(id) on delete cascade,
  user_name text not null default '',
  category text not null check (category in ('PAYMENT','DELIVERY','ACCOUNT','REFUND','SELLER_DISPUTE','OTHER')),
  subject text not null,
  description text not null default '',
  order_id bigint references public.orders(id) on delete set null,
  status text not null default 'OPEN' check (status in ('OPEN','IN_REVIEW','WAITING_USER','RESOLVED','CLOSED')),
  priority text not null default 'NORMAL' check (priority in ('LOW','NORMAL','HIGH')),
  admin_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.support_ticket_messages (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.support_tickets(id) on delete cascade,
  author_id bigint not null references public.profiles(id) on delete cascade,
  author_name text not null default '',
  author_role text not null default 'BUYER' check (author_role in ('BUYER','SELLER','ADMIN')),
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.product_appeals (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  product_id bigint not null references public.products(id) on delete cascade,
  seller_id bigint not null references public.profiles(id) on delete cascade,
  reason text not null,
  status text not null default 'PENDING' check (status in ('PENDING','APPROVED','REJECTED')),
  admin_notes text,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

-- Per-listing engagement counters used by seller analytics. Views already exist
-- as products.view_count; these add the two buyer-intent signals.
alter table public.products
  add column if not exists likes integer not null default 0,
  add column if not exists cart_adds integer not null default 0,
  add column if not exists impressions integer not null default 0;

-- Seller-visible moderation state (admin approval of new / edited listings).
alter table public.products
  add column if not exists moderation_status text not null default 'APPROVED'
    check (moderation_status in ('APPROVED','PENDING','REJECTED','APPEALED')),
  add column if not exists rejection_reason text;

-- Counter increments are funnelled through one security-definer function so
-- anonymous shoppers cannot write arbitrary product fields, only these counters.
create or replace function public.increment_product_metric(p_product_id bigint, p_metric text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_metric = 'view' then
    update public.products set view_count = view_count + 1 where id = p_product_id;
  elsif p_metric = 'impression' then
    update public.products set impressions = impressions + 1 where id = p_product_id;
  elsif p_metric = 'like' then
    update public.products set likes = likes + 1 where id = p_product_id;
  elsif p_metric = 'cart' then
    update public.products set cart_adds = cart_adds + 1 where id = p_product_id;
  end if;
end;
$$;

revoke all on function public.increment_product_metric(bigint, text) from public;
grant execute on function public.increment_product_metric(bigint, text) to anon, authenticated;

create index if not exists support_tickets_user_idx on public.support_tickets (user_id, created_at desc);
create index if not exists support_tickets_status_idx on public.support_tickets (status, created_at desc);
create index if not exists support_ticket_messages_ticket_idx on public.support_ticket_messages (ticket_id, created_at);
create index if not exists product_appeals_status_idx on public.product_appeals (status, created_at desc);

alter table public.support_tickets enable row level security;
alter table public.support_ticket_messages enable row level security;
alter table public.product_appeals enable row level security;

-- Users read/write their own tickets; admins read all through the service role.
drop policy if exists "support_tickets_owner_read" on public.support_tickets;
create policy "support_tickets_owner_read" on public.support_tickets
  for select using (auth.uid() = (select auth_id from public.profiles where id = user_id));

drop policy if exists "support_tickets_owner_insert" on public.support_tickets;
create policy "support_tickets_owner_insert" on public.support_tickets
  for insert with check (auth.uid() = (select auth_id from public.profiles where id = user_id));

drop policy if exists "support_messages_owner_read" on public.support_ticket_messages;
create policy "support_messages_owner_read" on public.support_ticket_messages
  for select using (
    exists (
      select 1 from public.support_tickets t
      join public.profiles p on p.id = t.user_id
      where t.id = ticket_id and auth.uid() = p.auth_id
    )
  );

drop policy if exists "support_messages_owner_insert" on public.support_ticket_messages;
create policy "support_messages_owner_insert" on public.support_ticket_messages
  for insert with check (auth.uid() = (select auth_id from public.profiles where id = author_id));

-- Staff can triage every ticket/appeal from the admin dashboard.
drop policy if exists "support_tickets_admin_read" on public.support_tickets;
create policy "support_tickets_admin_read" on public.support_tickets
  for select using (
    exists (
      select 1 from public.profiles p
      where p.auth_id = auth.uid() and p.role in ('ADMIN','SUPER_ADMIN','MODERATOR')
    )
  );

drop policy if exists "support_tickets_admin_update" on public.support_tickets;
create policy "support_tickets_admin_update" on public.support_tickets
  for update using (
    exists (
      select 1 from public.profiles p
      where p.auth_id = auth.uid() and p.role in ('ADMIN','SUPER_ADMIN','MODERATOR')
    )
  );

drop policy if exists "support_messages_admin_read" on public.support_ticket_messages;
create policy "support_messages_admin_read" on public.support_ticket_messages
  for select using (
    exists (
      select 1 from public.profiles p
      where p.auth_id = auth.uid() and p.role in ('ADMIN','SUPER_ADMIN','MODERATOR')
    )
  );

drop policy if exists "product_appeals_admin_rw" on public.product_appeals;
create policy "product_appeals_admin_rw" on public.product_appeals
  for all using (
    exists (
      select 1 from public.profiles p
      where p.auth_id = auth.uid() and p.role in ('ADMIN','SUPER_ADMIN','MODERATOR')
    )
  )
  with check (
    exists (
      select 1 from public.profiles p
      where p.auth_id = auth.uid() and p.role in ('ADMIN','SUPER_ADMIN','MODERATOR')
    )
  );

drop policy if exists "product_appeals_owner_rw" on public.product_appeals;
create policy "product_appeals_owner_rw" on public.product_appeals
  for all using (auth.uid() = (select auth_id from public.profiles where id = seller_id))
  with check (auth.uid() = (select auth_id from public.profiles where id = seller_id));
