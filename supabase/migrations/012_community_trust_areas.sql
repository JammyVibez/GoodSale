-- ---------------------------------------------------------------------------
-- 6. Verification applications — richer detail for admins to review
-- ---------------------------------------------------------------------------
ALTER TABLE public.identity_verifications
  ADD COLUMN IF NOT EXISTS application_kind  text NOT NULL DEFAULT 'IDENTITY',
  ADD COLUMN IF NOT EXISTS business_name     text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS business_address  text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS documents         jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS reviewed_by       bigint REFERENCES public.profiles(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS reviewed_at       timestamptz,
  ADD COLUMN IF NOT EXISTS rejection_reason  text NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_identity_verifications_status ON public.identity_verifications(status);

-- Applicants may withdraw / update their own pending application.
DROP POLICY IF EXISTS identity_verifications_own_update ON public.identity_verifications;
CREATE POLICY identity_verifications_own_update ON public.identity_verifications
  FOR UPDATE TO authenticated
  USING (user_id = public.current_profile_id() AND status = 'PENDING')
  WITH CHECK (user_id = public.current_profile_id());

DROP POLICY IF EXISTS identity_verifications_own_delete ON public.identity_verifications;
CREATE POLICY identity_verifications_own_delete ON public.identity_verifications
  FOR DELETE TO authenticated
  USING (user_id = public.current_profile_id() AND status = 'PENDING');

-- ---------------------------------------------------------------------------
-- 7. Rider documents — every uploaded file in one reviewable place
-- ---------------------------------------------------------------------------
ALTER TABLE public.delivery_partners
  ADD COLUMN IF NOT EXISTS documents       jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS rejection_reason text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS reviewed_by     bigint REFERENCES public.profiles(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS reviewed_at     timestamptz;

-- ---------------------------------------------------------------------------
-- 8. Realtime — add the newly-live tables to the publication
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    BEGIN
      ALTER PUBLICATION supabase_realtime ADD TABLE public.message_reactions;
    EXCEPTION WHEN duplicate_object THEN NULL;
    END;
    BEGIN
      ALTER PUBLICATION supabase_realtime ADD TABLE public.calls;
    EXCEPTION WHEN duplicate_object THEN NULL;
    END;
    BEGIN
      ALTER PUBLICATION supabase_realtime ADD TABLE public.reports;
    EXCEPTION WHEN duplicate_object THEN NULL;
    END;
    BEGIN
      ALTER PUBLICATION supabase_realtime ADD TABLE public.service_areas;
    EXCEPTION WHEN duplicate_object THEN NULL;
    END;
  END IF;
END $$;

