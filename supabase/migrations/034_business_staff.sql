-- =============================================================================
-- 034 — Business staff access
-- Extends the existing business/account model with role-scoped staff access.
-- Rows are readable by the owner, the staff member and admins; every write is
-- performed by the service-role staff API after it checks the owner's Business
-- membership, so no client policy can grant access.
-- =============================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.business_staff (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  member_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  role text NOT NULL DEFAULT 'ANALYST',
  status text NOT NULL DEFAULT 'ACTIVE',
  invited_by bigint REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT business_staff_role_valid CHECK (role IN ('MANAGER', 'INVENTORY', 'ANALYST')),
  CONSTRAINT business_staff_status_valid CHECK (status IN ('ACTIVE', 'SUSPENDED')),
  CONSTRAINT business_staff_not_self CHECK (owner_id <> member_id),
  CONSTRAINT business_staff_unique_member UNIQUE (owner_id, member_id)
);
CREATE INDEX IF NOT EXISTS idx_business_staff_member ON public.business_staff(member_id);
CREATE INDEX IF NOT EXISTS idx_business_staff_owner ON public.business_staff(owner_id);

-- A person can be staff for several businesses, but only once per business.
CREATE UNIQUE INDEX IF NOT EXISTS idx_business_staff_member_unique
  ON public.business_staff(member_id, owner_id);

DROP TRIGGER IF EXISTS business_staff_set_updated_at ON public.business_staff;
CREATE TRIGGER business_staff_set_updated_at
  BEFORE UPDATE ON public.business_staff
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.business_staff ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS business_staff_read ON public.business_staff;
CREATE POLICY business_staff_read ON public.business_staff
  FOR SELECT TO authenticated
  USING (
    owner_id = public.current_profile_id()
    OR member_id = public.current_profile_id()
    OR public.is_admin()
  );

-- No INSERT/UPDATE/DELETE policies on purpose: the service-role staff API is the
-- only writer, so a client cannot add itself to a business or change its role.

NOTIFY pgrst, 'reload schema';
COMMIT;
